#!/usr/bin/env python
"""Generate ``studies/README.md`` -- an index of every study, by family and by number.

GitHub lists at most 1,000 entries of a directory, so past study ~990 the ``studies/``
page silently stops: the newest studies are unreachable by browsing. This index is the
way in. It is generated from ``docs/bench.json`` (itself built from the ledger in
``docs/REFERENCE.md`` and the family taxonomy in ``docs/bench.md`` by
``tools/make_bench_figures.py``), so it never needs hand edits.

    python tools/make_studies_index.py           # (re)write studies/README.md
    python tools/make_studies_index.py --check   # exit 1 if it is stale (CI)

``--check`` also fails if a study directory is missing from ``docs/bench.json`` -- an
index that leaves studies out is the problem it exists to solve. Pure stdlib.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BENCH = os.path.join(ROOT, "docs", "bench.json")
STUDIES = os.path.join(ROOT, "studies")
OUT = os.path.join(STUDIES, "README.md")


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def load() -> list[dict]:
    with open(BENCH, encoding="utf-8") as fh:
        bench = json.load(fh)
    by_num: dict[int, dict] = {}
    for st in bench.get("studies", []) + bench.get("special", []):
        m = re.search(r"studies/([^/]+)/?$", st["href"])
        if not m:
            raise SystemExit(f"bench.json: unexpected href {st['href']!r}")
        by_num.setdefault(st["num"], {**st, "dir": m.group(1)})
    return [by_num[n] for n in sorted(by_num)]


def render(rows: list[dict]) -> str:
    fams: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        fams[r.get("family") or "Unclassified"].append(r)
    order = sorted(fams, key=lambda f: (f in ("Unclassified", "Pre-registered"), f.lower()))
    out = [
        "# Studies index",
        "",
        "<!-- Generated by tools/make_studies_index.py from docs/bench.json -- do not edit. -->",
        "",
        f"All **{len(rows)}** studies on the bench. GitHub stops listing a folder after "
        "1,000 entries, so this page is the reliable way in. The verdicts, claims and "
        "families come from the ledger ([`docs/REFERENCE.md`](../docs/REFERENCE.md)) and "
        "the family map ([`docs/bench.md`](../docs/bench.md)).",
        "",
        "- [By number](#by-number)",
        "- [By family](#by-family)",
        "",
        "## By number",
        "",
    ]
    hundreds: dict[int, list[dict]] = defaultdict(list)
    for r in rows:
        hundreds[r["num"] // 100].append(r)
    for h in sorted(hundreds):
        lo, hi = h * 100, h * 100 + 99
        links = " · ".join(f"[{r['num']}]({r['dir']}/)" for r in hundreds[h])
        out += [f"**{lo}–{hi}** — {links}", ""]
    out += ["## By family", ""]
    for f in order:
        out.append(f"- [{f}](#{_anchor(f)}) ({len(fams[f])})")
    out.append("")
    for f in order:
        out += [f"### {f}", "", "| # | Study | The claim | Signal | Tradability |",
                "|--:|---|---|---|---|"]
        for r in fams[f]:
            out.append(f"| {r['num']} | [{_cell(r['name'])}]({r['dir']}/) | "
                       f"{_cell(r['claim'])} | {_cell(r['signal'])} | "
                       f"{_cell(r['tradability'])} |")
        out.append("")
    return "\n".join(out)


def _anchor(title: str) -> str:
    """GitHub's heading anchor: lowercase, drop punctuation, spaces to hyphens."""
    a = re.sub(r"[^\w\- ]", "", title.lower())
    return a.replace(" ", "-")


def missing_dirs(rows: list[dict]) -> list[str]:
    listed = {r["dir"] for r in rows}
    return sorted(d for d in os.listdir(STUDIES)
                  if re.match(r"\d+-", d) and os.path.isdir(os.path.join(STUDIES, d))
                  and d not in listed)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 if studies/README.md is stale or incomplete")
    args = ap.parse_args(argv)
    rows = load()
    text = render(rows)
    missing = missing_dirs(rows)
    if args.check:
        ok = True
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("studies/README.md is stale: run python tools/make_studies_index.py")
            ok = False
        if missing:
            print(f"{len(missing)} study dir(s) absent from docs/bench.json "
                  f"(run python tools/make_bench_figures.py): {', '.join(missing[:10])}")
            ok = False
        if ok:
            print(f"studies/README.md is current ({len(rows)} studies).")
        return 0 if ok else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(rows)} studies)")
    if missing:
        print(f"warning: {len(missing)} study dir(s) absent from docs/bench.json: "
              f"{', '.join(missing[:10])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
