"""Beat-7 worked complement on the real tape — the defence stack (residualise *and* vol-manage).

Two independent crash defences: residualising sheds the beta-driven tail, vol-scaling sheds the
regime-clustered remainder. This script measures whether they compose on the real S&P 500 and writes
`docs/extension.md`.

    python examples/extension.py            # cache-only
    python examples/extension.py --fetch
"""

import argparse
import os
import sys

_STUDY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _STUDY)
sys.path.insert(0, os.path.abspath(os.path.join(_STUDY, "..", "..")))

from clean_slate import data, extension
from quantlab.repro import DEFAULT_AS_OF, as_of, fingerprint

OUT = os.path.join(_STUDY, "docs", "extension.md")
COST_BPS = 5.0


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--fetch", action="store_true")
    args = ap.parse_args()
    rets = data.fetch_panel(fetch=args.fetch)
    if rets.empty:
        print("[skip] no cached S&P 500 panel -- run with --fetch first."); return
    rets = as_of(rets, DEFAULT_AS_OF)
    fp = fingerprint(rets.round(6))
    st = extension.defence_stack(rets, cost_bps=COST_BPS)
    for k in ("total", "residual", "residual_vol_managed"):
        p = st[k]
        print(f"{k:22s}: Sharpe {p['sharpe']:+.2f}, skew {p['skew']:+.2f}, DD {p['max_drawdown_pct']:.0f}%")
    _write(OUT, st, fp, DEFAULT_AS_OF, rets.index.min().date(), rets.index.max().date(), rets.shape[1])
    print(f"\nwrote {OUT}")


def _write(path, st, fp, asof, lo, hi, n_stocks):
    def row(name, k):
        p = st[k]
        return f"| {name} | {p['sharpe']:+.2f} | {p['skew']:+.2f} | {p['worst_month_pct']:+.1f}% | {p['max_drawdown_pct']:.0f}% |"
    text = f"""# Beat 7 — worked complement: the defence stack (Study 25, Clean-Slate)

*Generated by [`examples/extension.py`](../examples/extension.py) on the current S&P 500. As-of
**{asof}**, {n_stocks} names, {lo} → {hi}, fingerprint `{fp}`.*

## Two crash defences that compose

Momentum's crash has two sources: the **systematic** exposure (after a market crash the book is short
the market just as it rebounds) and the **regime-clustered volatility** (crashes happen when the factor's
own vol is high). Residualising attacks the first; vol-scaling attacks the second. Do they stack?

| book | Sharpe | skew | worst month | max drawdown |
|---|---|---|---|---|
{row("total momentum", "total")}
{row("residual momentum", "residual")}
{row("residual + vol-managed", "residual_vol_managed")}

Residualising (a 1-factor, market residual) lifts the alpha point estimate but on its own does not dent
the drawdown — the value-driven crash needs factors we don't have here. Vol-management does the heavy
lifting on the tail. **Stacked** the drawdown falls from **{st['total']['max_drawdown_pct']:.0f}%** to
**{st['residual_vol_managed']['max_drawdown_pct']:.0f}%** while the Sharpe *rises* from
**{st['total']['sharpe']:+.2f}** to **{st['residual_vol_managed']['sharpe']:+.2f}**.

**Takeaway.** `WEAK` / `FRAGILE` / `Unproven here` survives the worked complement. The crash that made
[Study 24](../../24-stampede/) `FRAGILE` is *engineerable* — two cheap, independent overlays compose to
cut it by more than half. The part that doesn't yield to engineering is the one that matters most: the
*premium itself* is faint on the modern large-cap sample, residual or not.
"""
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


if __name__ == "__main__":
    main()
