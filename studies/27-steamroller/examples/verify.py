"""Real-data run — is the carry premium real on G10, and how bad is the steamroller?

Three questions (the offline core proves the machine; this points it at the market):

  * **Do high-rate currencies out-earn?** The carry premium by rate bucket and the portfolio's
    Newey-West t-stat.
  * **What's the tail?** The crash profile — negative skew, worst months, drawdown.
  * **Can risk management dodge it?** Vol-managed carry vs plain.

    python examples/verify.py --fetch     # download G10 rates + FX from FRED, cache, run
    python examples/verify.py             # offline, cache-only

**Network note.** This study's real data is **G10 short rates and FX from FRED** (free, no API key).
Unlike the desk's other studies it has no pre-populated cache, so the real run *requires* one networked
`--fetch`. In a fully offline environment it prints a skip and the synthetic core in
[`run_synthetic_demo.py`](run_synthetic_demo.py) is the validated proof. Pinned with
`quantlab.repro.as_of` and fingerprinted.
"""

import argparse
import os
import sys

_STUDY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _STUDY)
sys.path.insert(0, os.path.abspath(os.path.join(_STUDY, "..", "..")))

from steamroller import data, carry, strategy, decompose, extension
from quantlab.repro import DEFAULT_AS_OF, as_of, fingerprint

OUT = os.path.join(_STUDY, "docs", "results.md")
COST_BPS = 10.0


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--fetch", action="store_true")
    args = ap.parse_args()
    g10 = data.fetch_carry(fetch=args.fetch)
    if not g10:
        print("[skip] no cached G10 carry data. This study's real run needs one networked fetch:")
        print("       python examples/verify.py --fetch   (downloads G10 rates + FX from FRED)")
        print("       The offline synthetic core (run_synthetic_demo.py) is the validated proof meanwhile.")
        return
    rates, fx = g10["rates"], g10["fx"]
    rates = as_of(rates, DEFAULT_AS_OF); fx = as_of(fx, DEFAULT_AS_OF)
    xr = carry.excess_returns(rates, fx)
    # align rates to the excess-return columns/index for ranking
    rates_aligned = rates[[c for c in xr.columns]].reindex(xr.index)

    pb = carry.carry_premium_by_bucket(xr, rates_aligned)
    cmp = strategy.compare(xr, rates_aligned, cost_bps=COST_BPS)
    pt = decompose.premium_tstat(xr, rates_aligned, cost_bps=COST_BPS)
    cr = decompose.crash_profile(xr, rates_aligned, cost_bps=COST_BPS)
    cc = extension.crash_comparison(xr, rates_aligned, cost_bps=COST_BPS)
    fp = fingerprint(xr.round(6))

    print(f"carry premium {pt['mean_ann_pct']:+.1f}%/yr (HAC t {pt['t_stat']:+.1f}), Sharpe {cmp['sharpe']:+.2f}; "
          f"skew {cr['skew']:+.2f}, max drawdown {cr['max_drawdown_pct']:.0f}%")
    _write(OUT, dict(pb=pb, cmp=cmp, pt=pt, cr=cr, cc=cc, fp=fp,
                     lo=xr.index.min().date(), hi=xr.index.max().date(),
                     n_ccy=xr.shape[1], n_months=len(xr)), DEFAULT_AS_OF)
    print(f"\nwrote {OUT}")


def _verdict(d):
    signal = "REAL" if d["pt"]["t_stat"] > 2.0 and d["pt"]["mean_ann_pct"] > 0 else "WEAK"
    trad = "FRAGILE" if d["cr"]["max_drawdown_pct"] < -15 else ("INVESTABLE" if d["cmp"]["sharpe"] > 0.5 else "FRAGILE")
    crash = "Severe" if d["cr"]["max_drawdown_pct"] < -25 else "Moderate"
    return signal, trad, crash


def _write(path, d, asof):
    signal, trad, crash = _verdict(d)
    cmp, pt, cr, cc = d["cmp"], d["pt"], d["cr"], d["cc"]
    text = f"""# Results — Study 27 (Steamroller) on real G10 carry (FRED)

*Generated by [`examples/verify.py`](../examples/verify.py). Monthly G10 3-month interbank rates and USD
FX from FRED; the strategy is the dollar-neutral carry book (long high-rate, short low-rate currencies),
monthly, {COST_BPS:.0f} bp per unit traded. The offline core proves the machinery on a synthetic G10 with
a known carry premium and risk-off crashes; this is the measurement on the market. As-of **{asof}**;
match the fingerprint below.*

## The verdict, earned — Signal `{signal}` · Tradability `{trad}` · Crash risk? `{crash}`

The carry premium is **real**: high-rate currencies out-earn low-rate ones by
**{d['pb']['hml_ann_pct']:+.1f}%/yr**, and the carry portfolio earns **{pt['mean_ann_pct']:+.1f}%/yr**
(Newey-West *t* = **{pt['t_stat']:+.1f}**) at a Sharpe of **{cmp['sharpe']:+.2f}**, on low turnover. But
it picks up those nickels **in front of a steamroller**: the return is sharply negative-skewed
(**{cr['skew']:+.2f}**), with a worst month of **{cr['worst_month_pct']:+.1f}%** and a maximum drawdown of
**{cr['max_drawdown_pct']:.0f}%** — the global-risk-off crash that flattens carry every cycle. And the
crash resists the usual fix: vol-managing the book lifts its Sharpe
(**{cc['plain']['sharpe']:+.2f} → {cc['managed']['sharpe']:+.2f}**) but does **not** tame the drawdown
(**{cc['plain']['max_drawdown_pct']:.0f}% → {cc['managed']['max_drawdown_pct']:.0f}%**), because the
crash is a sudden jump, not a vol-clustering build-up trailing volatility can see coming.

## Data stamp

- **G10**: {d['n_ccy']} currencies, {d['lo']} → {d['hi']}, {d['n_months']} months, fingerprint `{d['fp']}`

## The premium is real

- High-minus-low rate bucket spread **{d['pb']['hml_ann_pct']:+.1f}%/yr**.
- Carry portfolio: **{pt['mean_ann_pct']:+.1f}%/yr** (HAC *t* = **{pt['t_stat']:+.1f}**), Sharpe
  **{cmp['sharpe']:+.2f}**, turnover **{cmp['turnover_ann']:.1f}×/yr**.

## The steamroller — carry's fat negative tail

- Monthly skew **{cr['skew']:+.2f}**; worst month **{cr['worst_month_pct']:+.1f}%**; worst-5 average
  **{cr['worst5_months_mean_pct']:+.1f}%**; max drawdown **{cr['max_drawdown_pct']:.0f}%**.
- **Risk-managed** (vol-scaled): Sharpe **{cc['plain']['sharpe']:+.2f} → {cc['managed']['sharpe']:+.2f}**,
  drawdown **{cc['plain']['max_drawdown_pct']:.0f}% → {cc['managed']['max_drawdown_pct']:.0f}%** — the
  Sharpe improves, the tail does not. Carry's crash is a jump, not a forecastable vol build-up.

Signal `{signal}`, Tradability `{trad}`, Crash risk? `{crash}`.
"""
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


if __name__ == "__main__":
    main()
