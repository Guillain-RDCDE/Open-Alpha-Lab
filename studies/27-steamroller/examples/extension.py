"""Beat-7 worked complement on the real tape — does risk management dodge the steamroller?

Vol-targeting earned [Study 16](../../16-storm-shy/) the desk's only green and tamed momentum's crash in
[Study 24](../../24-stampede/). Does the same overlay protect the carry trade? This script builds the
vol-managed G10 carry book and compares its crash profile to the plain one, writing `docs/extension.md`.
Reads the desk's shared G10 cache (see examples/verify.py); `--fetch` only refills a missing cache, via
tools/fetch_altdata.py.

    python examples/extension.py            # offline, cache-only
    python examples/extension.py --fetch    # refill a missing cache (network)
"""

import argparse
import os
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

_STUDY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _STUDY)
sys.path.insert(0, os.path.abspath(os.path.join(_STUDY, "..", "..")))

from steamroller import data, carry, extension
from quantlab.repro import as_of, fingerprint

OUT = os.path.join(_STUDY, "docs", "extension.md")
COST_BPS = 10.0


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--fetch", action="store_true")
    args = ap.parse_args()
    g10 = data.fetch_carry(fetch=args.fetch)
    if not g10:
        print("[skip] no cached G10 data -- run examples/verify.py --fetch first (shared desk cache)."); return
    rates, fx = as_of(g10["rates"], data.DATA_AS_OF), as_of(g10["fx"], data.DATA_AS_OF)
    xr = carry.excess_returns(rates, fx)
    rates_aligned = rates[[c for c in xr.columns]].reindex(xr.index)
    fp = fingerprint(xr.round(6))
    cc = extension.crash_comparison(xr, rates_aligned, cost_bps=COST_BPS)
    for k in ("plain", "managed"):
        p = cc[k]; print(f"{k:8s}: Sharpe {p['sharpe']:+.2f}, skew {p['skew']:+.2f}, DD {p['max_drawdown_pct']:.0f}%")
    _write(OUT, cc, fp, data.DATA_AS_OF, xr.index.min().date(), xr.index.max().date(), xr.shape[1])
    print(f"\nwrote {OUT}")


def _write(path, cc, fp, asof, lo, hi, n_ccy):
    p, m = cc["plain"], cc["managed"]
    text = f"""# Beat 7 — worked complement: can risk management dodge the steamroller? (Study 27)

*Generated by [`examples/extension.py`](../examples/extension.py) on the real G10 carry tape (OECD MEI
short rates + yfinance FX, the desk's shared cache). As-of **{asof}**, {n_ccy} currencies, {lo} → {hi},
fingerprint `{fp}`. Both books are profiled on the same {cc['n_months']}-month window — the vol-managed
book only exists after its 12-month trailing-vol burn-in, so the plain book is re-windowed to match
(which is why the plain Sharpe here differs slightly from the full-sample headline).*

## The overlay that worked elsewhere — and doesn't here

Vol-targeting tamed the crash for equity ([Study 16](../../16-storm-shy/)) and momentum
([Study 24](../../24-stampede/)), because those crashes are preceded by *rising volatility* a trailing
estimate can see. Carry is different.

| | plain carry | vol-managed carry |
|---|---|---|
| Sharpe | {p['sharpe']:+.2f} | {m['sharpe']:+.2f} |
| monthly skew | {p['skew']:+.2f} | {m['skew']:+.2f} |
| worst month | {p['worst_month_pct']:+.1f}% | {m['worst_month_pct']:+.1f}% |
| max drawdown | {p['max_drawdown_pct']:.0f}% | {m['max_drawdown_pct']:.0f}% |

On the real tape the overlay is a **strict loss**: the Sharpe falls
(**{p['sharpe']:+.2f} → {m['sharpe']:+.2f}**), the worst month deepens
(**{p['worst_month_pct']:+.1f}% → {m['worst_month_pct']:+.1f}%**) and the drawdown nearly doubles
(**{p['max_drawdown_pct']:.0f}% → {m['max_drawdown_pct']:.0f}%**) — because trailing vol reads the calm
2003–07 carry build-up as safety, levers up, and rides straight into the 2008 jump. (On the synthetic
control the overlay at least lifted the Sharpe while deepening the tail; the real tape is harsher.)

**Takeaway.** `WEAK` / `FRAGILE` / `Severe` survives the worked complement — and the complement sharpens
*why* the crash is `Severe`: it is the one tail the desk's usual risk overlay can't forecast. Carry's
premium is compensation for a jump you have to be willing (and able) to hold through; the honest fixes
are diversification (Study 36 measures exactly that), options-based tail hedges, or conditioning on a
risk-off indicator — forks for the next contributor, not a vol target.
"""
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


if __name__ == "__main__":
    main()
