"""Beat-7 worked complement on the real tape — the bias survives every check except causality.

A practitioner who saw the spectacular two-sided result would 'robustness-check' it: charge more cost,
vary the smoothing lam. We show those checks all *pass* — the two-sided Sharpe stays large — which is
exactly what makes the trap dangerous: every test passes except the one that matters (use only past
data). Writes `docs/extension.md`.

    python examples/extension.py            # cache-only
    python examples/extension.py --fetch
"""

import argparse
import os
import sys

import pandas as pd

_STUDY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _STUDY)
sys.path.insert(0, os.path.abspath(os.path.join(_STUDY, "..", "..")))

from crystal_ball import data, extension, decompose
from quantlab.repro import DEFAULT_AS_OF, as_of, fingerprint

OUT = os.path.join(_STUDY, "docs", "extension.md")
HEADLINE = "SPY"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fetch", action="store_true")
    args = ap.parse_args()

    closes = data.fetch_closes(fetch=args.fetch)
    if not closes:
        print("[skip] no cached closes -- run with --fetch first.")
        return
    closes = {tk: as_of(c.to_frame(), DEFAULT_AS_OF)["close"] for tk, c in closes.items()}
    head = closes[HEADLINE]
    fp = fingerprint(pd.DataFrame(closes).round(6))

    ls = extension.lam_sweep(head)
    cs = extension.cost_robustness(head)
    print(ls.round(2).to_string()); print(cs.round(2).to_string())

    _write(OUT, ls, cs, fp, DEFAULT_AS_OF, head.index.min().date(), head.index.max().date(), HEADLINE)
    print(f"\nwrote {OUT}")


def _write(path, ls, cs, fp, asof, lo, hi, head):
    lam_rows = "\n".join(f"| {k:.0e} | {r['two_sided_sharpe']:+.2f} | {r['one_sided_sharpe']:+.2f} |"
                         for k, r in ls.iterrows())
    cost_rows = "\n".join(f"| {int(k)} | {r['two_sided_sharpe']:+.2f} | {r['one_sided_sharpe']:+.2f} |"
                          for k, r in cs.iterrows())
    text = f"""# Beat 7 — worked complement: the bias survives every check but causality (Study 22, Crystal-Ball)

*Generated by [`examples/extension.py`](../examples/extension.py) on real {head}. As-of **{asof}**,
{lo} → {hi}, fingerprint `{fp}`.*

## Every robustness check passes — which is the danger

Faced with the two-sided book's spectacular Sharpe, the natural next step is to stress it: charge more
cost, vary the HP smoothing λ. The point of this complement is that **all of those checks pass** — the
look-ahead edge is so large it laughs them off — so a careful-looking research process can validate a
strategy that is pure artefact. The only check that kills it is the one rarely run: *recompute the
filter using only past data.*

### Across smoothing λ

| λ | two-sided Sharpe | one-sided Sharpe |
|---|---|---|
{lam_rows}

### Across transaction cost (bps per turn)

| cost | two-sided Sharpe | one-sided Sharpe |
|---|---|---|
{cost_rows}

At every λ and every cost the two-sided Sharpe stays large and the one-sided stays ~0. The bias is not
a tuning artefact you can stumble out of — it is the filter peeking, present at every setting.

**Takeaway.** `NONE` / `MIRAGE` / `BUSTED` survives the worked complement. The lesson generalises far
past the HP filter: any indicator fit on the whole sample (a two-sided filter, a normalisation by
full-sample mean/vol, a regression on all data) smuggles the future into the past. The fix is always the
same — compute it causally — and the test is always the same — does perturbing a *future* point change a
*past* signal value.
"""
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


if __name__ == "__main__":
    main()
