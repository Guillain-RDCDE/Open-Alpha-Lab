"""Real-data run — is the HP-cycle mean-reversion edge real, or is it look-ahead?

The whole study is one comparison, run on real ETFs:

  * **The spectacular backtest** — trade the *two-sided* HP cycle (long when price is below its smooth
    trend). It looks glorious.
  * **The honest version** — the same rule on the *one-sided* (causal) HP cycle, which uses no future
    data. It is what you could actually trade.
  * **The smoking gun** — the correlation of today's cycle with *future* returns: the two-sided cycle
    was built from them, so it correlates; the one-sided cannot.

    python examples/verify.py --fetch     # populate the close cache (network)
    python examples/verify.py             # offline, cache-only

Network lives only behind `--fetch`. Pinned with `quantlab.repro.as_of` and fingerprinted. Data choice:
split-only closes, used in log space; both filters are charged the identical series, so the only
difference is *what data the filter is allowed to see*.
"""

import argparse
import os
import sys

import pandas as pd

_STUDY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _STUDY)
sys.path.insert(0, os.path.abspath(os.path.join(_STUDY, "..", "..")))

from crystal_ball import data, decompose, strategy
from quantlab.repro import DEFAULT_AS_OF, as_of, fingerprint

OUT = os.path.join(_STUDY, "docs", "results.md")
COST_BPS = 1.0
LAM = 1e6
HEADLINE = "SPY"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fetch", action="store_true")
    args = ap.parse_args()

    closes = data.fetch_closes(fetch=args.fetch)
    if not closes:
        print("[skip] no cached closes -- run with --fetch first.")
        return
    closes = {tk: as_of(c.to_frame(), DEFAULT_AS_OF)["close"] for tk, c in closes.items()}

    per = {}
    for tk, c in closes.items():
        lb = decompose.lookahead_bias(c, cost_bps=COST_BPS, lam=LAM)
        per[tk] = lb
        print(f"{tk}: two-sided SR {lb['two_sided_sharpe']:+.2f} (t{lb['two_sided_t']:+.1f}) | "
              f"one-sided SR {lb['one_sided_sharpe']:+.2f} (t{lb['one_sided_t']:+.1f})")

    head = closes[HEADLINE]
    leak = decompose.future_leakage(head, lam=LAM)
    honest = decompose.honest_edge(head, cost_bps=COST_BPS, lam=LAM)

    allc = pd.DataFrame(closes)
    fp = fingerprint(allc.round(6))
    _write(OUT, dict(per=per, head=HEADLINE, leak=leak, honest=honest, fp=fp,
                     lo=allc.index.min().date(), hi=allc.index.max().date(), n=len(allc.columns)), DEFAULT_AS_OF)
    print(f"\nwrote {OUT}")


def _write(path, d, asof):
    per_rows = "\n".join(
        f"| {tk} | {v['two_sided_sharpe']:+.2f} | {v['two_sided_t']:+.1f} | {v['one_sided_sharpe']:+.2f} | {v['one_sided_t']:+.1f} |"
        for tk, v in d["per"].items()
    )
    leak_rows = "\n".join(
        f"| {h} | {d['leak'][h]['two_sided_corr']:+.2f} | {d['leak'][h]['one_sided_corr']:+.2f} |"
        for h in d["leak"]
    )
    head = d["head"]; hv = d["per"][head]
    text = f"""# Results — Study 22 (Crystal-Ball) on real ETFs

*Generated by [`examples/verify.py`](../examples/verify.py). Daily split-only closes, in log space; the
strategy is HP-cycle mean reversion (`w = -sign(cycle)`, long when price is below its HP trend),
{COST_BPS:.0f} bp per position change, λ = {LAM:.0e}. The **two-sided** book uses the classic HP filter
(trend uses the whole series, future included); the **one-sided** book uses a causal, trailing-window HP
(past only). The offline core proves the trap on a synthetic random walk; this is the measurement on the
market. As-of **{asof}**; match the fingerprint below.*

## The verdict, earned — Signal `NONE` · Tradability `MIRAGE` · Look-ahead bias? `BUSTED`

Detrend a price with the textbook (two-sided) HP filter and trade the cycle's mean reversion, and you
get a *spectacular* backtest — on real {head}, a Sharpe of **{hv['two_sided_sharpe']:+.2f}** at a
Newey-West *t* of **{hv['two_sided_t']:+.1f}**. It is entirely **fool's foresight**. The two-sided HP
trend at any day is computed from the *entire* series, so the cycle "knows" where price is headed: its
correlation with the **next 5-day return** is **{d['leak'][5]['two_sided_corr']:+.2f}** — it is literally
built from the future it then "predicts". Recompute the filter **causally** (trailing window, past data
only) and the edge evaporates: one-sided Sharpe **{hv['one_sided_sharpe']:+.2f}** (*t* =
**{hv['one_sided_t']:+.1f}**), forward-return correlation **{d['leak'][5]['one_sided_corr']:+.2f}**.
Nothing real survives the moment you stop peeking. A textbook backtest trap, busted.

## Data stamp

- **Basket** ({d['n']} ETFs): {d['lo']} → {d['hi']}, fingerprint `{d['fp']}`

## Two-sided (peeking) vs one-sided (causal), per instrument

| asset | two-sided Sharpe | two-sided *t* | one-sided Sharpe | one-sided *t* |
|---|---|---|---|---|
{per_rows}

Every instrument shows the same pattern: a huge, "highly significant" two-sided Sharpe, and a one-sided
Sharpe indistinguishable from zero. The *t*-stat is not measuring an edge — it is measuring how much the
filter peeked.

## The smoking gun — cycle vs *future* returns ({head})

Correlation of today's HP cycle with the forward h-day return:

| horizon (days) | two-sided cycle | one-sided cycle |
|---|---|---|
{leak_rows}

The two-sided cycle is strongly correlated with returns that **hadn't happened yet** when (in reality)
the position would have been taken — because the filter used them. The one-sided cycle, which can't see
them, is ~uncorrelated. That is look-ahead, measured directly.

## What survives the peek-stop ({head})

The honest, causal book: Sharpe **{d['honest']['sharpe']:+.2f}**, annual return
**{d['honest']['ann_return']:+.1%}**, Newey-West *t* = **{d['honest']['t_stat']:+.1f}** — no edge. The
HP-filter mean-reversion strategy is `NONE` / `MIRAGE`; the only thing the two-sided version measured
was its own look-ahead. `BUSTED`.
"""
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


if __name__ == "__main__":
    main()
