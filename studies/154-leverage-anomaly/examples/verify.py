def _hac_tstat(series):
    """Newey-West HAC t-stat for a short annual series."""
    import numpy as np
    import pandas as pd
    r = pd.Series(series).astype(float).dropna().to_numpy()
    n = len(r)
    if n < 3:
        return float("nan")
    mu = r.mean()
    e = r - mu
    lags = max(1, int(__import__("math").floor(4.0 * (n / 100.0) ** (2.0 / 9.0))))
    lrv = float(e @ e) / n
    for k in range(1, lags + 1):
        w = 1.0 - k / (lags + 1.0)
        lrv += 2.0 * w * float(e[k:] @ e[:-k]) / n
    se = (max(lrv, 0.0) / n) ** 0.5
    return float(mu / se) if se > 0 else float("nan")


def main():
    print("Study 154 — Leverage-Anomaly  |  real-tape verification")
    print(f"As-of: {date.today()}")
    print()

    lev1, lev2, fwd_ret = data.fetch_panel()

    if lev1.empty:
        print("EDGAR cache not found — run from repo root with caches present.")
        sys.exit(1)

    # -------------------------------------------------------------------
    # LEV1: LTD / Assets
    # -------------------------------------------------------------------
    sp1 = st.quintile_spread(lev1, fwd_ret, q=0.20, low_is_good=True)
    s1 = st.summarize(sp1["spread"])
    exc1 = st.random_portfolio_excess(lev1, fwd_ret, n_draws=500, seed=154)
    s1_rand_mean = float(exc1.mean())

    print("=== LEV1: LTD / Assets ===")
    print(f"  Years: {sp1.index.min()} – {sp1.index.max()}  |  n_annual = {s1['n']}")
    print(f"  Low-minus-high  mean={s1['mean']*100:+.2f}%/yr  t={s1['tstat']:+.2f}  "
          f"hit={s1['hit_rate']*100:.0f}%  Sharpe={s1['sharpe']:+.2f}")
    print(f"  Random control excess (mean): {s1_rand_mean*100:+.2f}%/yr")

    # -------------------------------------------------------------------
    # LEV2: Liabilities / Equity (D/E)
    # -------------------------------------------------------------------
    sp2 = st.quintile_spread(lev2, fwd_ret, q=0.20, low_is_good=True)
    s2 = st.summarize(sp2["spread"])
    exc2 = st.random_portfolio_excess(lev2, fwd_ret, n_draws=500, seed=154)
    s2_rand_mean = float(exc2.mean())

    print()
    print("=== LEV2: Liabilities / Equity (D/E ratio) ===")
    print(f"  Years: {sp2.index.min()} – {sp2.index.max()}  |  n_annual = {s2['n']}")
    print(f"  Low-minus-high  mean={s2['mean']*100:+.2f}%/yr  t={s2['tstat']:+.2f}  "
          f"hit={s2['hit_rate']*100:.0f}%  Sharpe={s2['sharpe']:+.2f}")
    print(f"  Random control excess (mean): {s2_rand_mean*100:+.2f}%/yr")

    # -------------------------------------------------------------------
    # Fingerprints
    # -------------------------------------------------------------------
    fp_lev1 = data.fingerprint(lev1)
    fp_lev2 = data.fingerprint(lev2)
    fp_fwd = data.fingerprint(fwd_ret)

    print()
    print(f"  fp(LTD/Assets panel):        {fp_lev1}")
    print(f"  fp(D/E panel):               {fp_lev2}")
    print(f"  fp(fwd_ret panel):           {fp_fwd}")

