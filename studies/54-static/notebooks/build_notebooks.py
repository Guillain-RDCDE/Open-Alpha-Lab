        md("### 4.3 Why — the high-risk axis, on large caps"),
        md("Idio-vol and MAX ([53 Jackpot](../../53-jackpot/)) measure the same thing; both invert because "
           "(1) high idio-vol = high-risk growth, which *won* on large caps 2000–2026 (cf. "
           "[43 Free-Lunch](../../43-free-lunch/)); (2) survivorship keeps the high-vol *winners*; (3) the "
           "puzzle is documented in micro-caps (Hou-Xue-Zhang 2020). **H₃ rejected.**"),
