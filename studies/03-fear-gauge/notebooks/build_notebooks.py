            "**uninvestable** (short-skew premium + a martingale that ignores 2008).\n\n"
            "> ⚠️ **Not investment advice.** Reproducible research; fixed seeds. Data: "
            "^GSPC, SPY, ^VIX from Yahoo! Finance (first run hits the network, later runs use "
