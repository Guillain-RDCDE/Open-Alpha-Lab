            "FAMILY = {\n"
            "    'V1_level_30': triggers.level(vix, 30),\n"
            "    'V1_level_40': triggers.level(vix, 40),\n"
            "    'V1_level_50': triggers.level(vix, 50),\n"
            "    'V2_spike':    triggers.spike(vix),\n"
