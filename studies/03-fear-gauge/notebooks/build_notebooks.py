            "## 6 · Could you trade it — the martingale's risk of ruin\n\n"
            "Spot VIX isn't investable; the buy side is SPY (or a vol product with roll/decay). "
            "The decisive risk is the sizing rule: **\"double down at 50\"** adds capital as the "
            "tail fattens. We run it through history and report the probability it hits a ruin "
