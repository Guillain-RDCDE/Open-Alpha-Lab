# 02 — FOR THE QUANTS   (the rigorous layer of the same seven beats)
# ===========================================================================
def build_quants():
    cells = [
        md(
            "# Fear-Gauge — the teardown 🌡️🔬\n"
            "### Buying the VIX spike: random-day null, the price-drop control, clustering, "
            "selection, and the martingale's ruin\n\n"
            "The rigorous companion to [`01_for_the_curious.ipynb`](01_for_the_curious.ipynb). "
            "Same seven beats, full method. The thesis we're testing: the post-spike rebound "
            "is **statistically real** (it's the variance risk premium) but **uninvestable** "
            "(short-skew premium + a martingale that ignores 2008).\n\n"
            "> ⚠️ **Not investment advice.** Reproducible research; fixed seeds. First run "
            "downloads ^GSPC, SPY, ^VIX from Yahoo! Finance, then caches to `../_cache/`."
        ),
        code(BOOT),
        code(
            "# Both faces of the market + the gauge. Spot for stats, ETF for the cost layer.\n"
            "spy, vix_spy = data.aligned('SPY')\n"
            "for nm, (mkt, vx) in {'^GSPC': (spx, vix), 'SPY': (spy, vix_spy)}.items():\n"
            "    print(f\"{nm:6s} {len(mkt):>6,} sessions  {mkt.index.min().date()} -> {mkt.index.max().date()}\")"
        ),

        # ---- BEAT 1 ----------------------------------------------------------
        md(
            "## 1 · The claim, as testable hypotheses\n\n"
            "H₁ (level): E[r_{t→t+h} | VIX_t ≥ 30] > E[r_{t→t+h}] with HAC-robust t > 2.\n"
            "H₁ (spike): same, conditioned on ΔVIX_t ≥ +30%.\n"
            "H₀: excess ≈ 0 — the forward return is drift + beta. Horizons h ∈ {1, 5, 21} to "
            "match the chart's +1d/+1w/+1m exactly."
        ),
        code(
            "FAMILY = {\n"
            "    'V1_level_30': triggers.level(vix, 30),\n"
            "    'V1_level_40': triggers.level(vix, 40),\n"
            "    'V1_level_50': triggers.level(vix, 50),\n"
            "    'V2_spike':    triggers.spike(vix),\n"
            "    'V3_low_base': triggers.spike_from_base(vix, base_max=20),\n"
            "    'V3_high_base':triggers.spike_from_base(vix, base_min=30),\n"
            "}\n"
            "events = {k: triggers.first_crossings(v, cooldown=21) for k, v in FAMILY.items()}\n"
            "pd.Series({k: int(v.sum()) for k, v in events.items()}, name='fresh events').to_frame()"
        ),

        # ---- BEAT 3/4 — the null --------------------------------------------
        md(
            "## 3–4 · The random-day null, across the whole family\n\n"
            "`p_greater` = P(a random basket of the same size beats the conditional mean). "
            "Small ⇒ the gauge adds something beyond drift."
        ),
        code(
            "rows = []\n"
            "for name, sig in events.items():\n"
            "    t = benchmark.conditional_vs_unconditional(spx, sig, horizons=(1, 5, 21), n_iter=2000)\n"
            "    for h, r in t.iterrows():\n"
            "        rows.append({'trigger': name, 'h': h, 'n': int(r.n_events),\n"
            "                     'excess': r.excess, 'p_greater': r.p_greater})\n"
            "null_tbl = pd.DataFrame(rows).set_index(['trigger', 'h'])\n"
            "null_tbl"
        ),

        # ---- BEAT 4 — the cross-study control --------------------------------
        md(
            "## 4 · The cross-study control — does VIX beat the price drop?\n\n"
            "The confound that makes this study hard: VIX-high ≈ price-low. We pit each VIX "
            "trigger against Study 02's T1 (a −3% close) on the *same* forward returns, with a "
            "label-permutation test on the gap. **A VIX trigger that clears the random-day "
            "null but not this control is the falling knife in vol coordinates.**"
        ),
        code(
            "t1 = triggers.first_crossings(spx['r_cc'] <= -0.03, cooldown=21)\n"
            "ctrl = {}\n"
            "for name in ['V1_level_30', 'V2_spike', 'V3_high_base']:\n"
            "    ctrl[name] = benchmark.excess_vs_alternative(spx, events[name], t1, horizons=(1, 5, 21))\n"
            "pd.concat(ctrl, names=['trigger', 'h'])[['mean_signal', 'mean_alt', 'gap', 'p_signal_gt_alt']]"
        ),

        # ---- BEAT 4 — clustering + selection ---------------------------------
        md(
            "## 4 · Clustering and selection — the two ways the chart cheats\n\n"
            "**(a) Clustering.** 4 of the chart's 23 events are Feb–Mar 2020. The iid "
            "permutation overstates significance; a block bootstrap that resamples contiguous "
            "months gives an honest CI on the excess."
        ),
        code(
            "boot = {name: robustness.block_bootstrap_excess(spx, events[name], horizon=21,\n"
            "                                                 block=21, n_iter=2000)\n"
            "        for name in ['V1_level_30', 'V2_spike', 'V3_high_base']}\n"
            "pd.DataFrame(boot).T[['mean', 'ci_low', 'ci_high', 'p_excess_le_0']]"
        ),
        md(
            "**(b) Selection.** The viral chart's window (2016–2026) excludes 2008. Recompute "
            "the same excess on the cherry-picked window vs the full history — if it shrinks or "
            "flips, the edge was a property of the *window*, not the *signal*."
        ),
        code(
            "robustness.window_sensitivity(spx, events['V2_spike'], horizon=21)"
        ),

        # ---- BEAT 5 ----------------------------------------------------------
        md(
            "## 5 · The verdict, with the numbers\n\n"
            "Collate the decisive figures: random-day `p_greater`, the price-drop `gap` and its "
            "p-value, the block-bootstrap CI, and the window swing. Fill the README's beat-5 "
            "stamps from this cell once it's run on live data.\n\n"
            "Expected shape: **Signal `REAL`** at short horizons (vol mean-reversion is robust) "
            "but **Tradability `MIRAGE`/`FRAGILE`** — the excess is VRP, it doesn't clearly "
            "beat the price drop, and it's carried by a handful of clustered crises."
        ),

        # ---- BEAT 6 — capacity + ruin ----------------------------------------
        md(
            "## 6 · Could you trade it — the martingale's risk of ruin\n\n"
            "Spot VIX isn't investable; the buy side is SPY (or a vol product with roll/decay). "
            "The decisive risk is the sizing rule: **\"double down at 50\"** adds capital as the "
            "tail fattens. We run it through history and report the probability it hits a ruin "
            "drawdown before recovering — on the full sample, and on the no-2008 window that "
            "sells it."
        ),
        md(
            "**First, trade the level honestly.** Buy SPY at the VIX≥30 cross, hold a "
            "month, charge realistic costs (including entry slippage into the spike). The "
            "Sharpe is modest and you sit in cash ~88% of the time — market-timing that "
            "underperforms buy-and-hold, not an edge."
        ),
        code(
            "sig30 = triggers.first_crossings(triggers.level(vix, 30), cooldown=21)\n"
            "res = backtest.run(spx, sig30, exits.ExitRule(max_hold=21), backtest.CostModel())\n"
            "print({k: (round(v, 4) if isinstance(v, float) else v) for k, v in res.stats.items()\n"
            "       if k in ('n_trades','cagr','sharpe','max_drawdown','win_rate','exposure')})\n"
            "backtest.cost_sweep(spx, sig30, exits.ExitRule(max_hold=21))  # entry-slippage sweep"
        ),
        md(
            "**Then watch the family scan lie.** Scan every (trigger × exit) and the best "
            "cell posts an absurd Sharpe — on a handful of trades. Deflate it for the number "
            "of configs tried and it collapses back into noise. *Never read the best row.*"
        ),
        code(
            "fam = {'V1_30': triggers.level(vix,30), 'V1_50': triggers.level(vix,50),\n"
            "       'V2_spike': triggers.spike(vix), 'V3_high': triggers.spike_from_base(vix, base_min=30)}\n"
            "scan = backtest.family_scan(spx, fam, exits.default_grid())\n"
            "top = scan.iloc[0]\n"
            "dsr = robustness.deflated_sharpe(top.sharpe, n_trials=len(scan), n_obs=int(top.avg_hold_days*top.n_trades))\n"
            "print(f\"best cell: {top.trigger} / {top.exit}  Sharpe={top.sharpe:.1f} on {int(top.n_trades)} trades\")\n"
            "print(f\"deflated Sharpe (P it isn't luck over {len(scan)} configs): {dsr:.3f}\")\n"
            "scan.head(5)"
        ),
        md(
            "**Now the martingale.** \"Double down at 50\", held a fixed quarter, tracking the "
            "deepest drawdown along the way — on the full sample versus the no-2008 window "
            "that sells the rule."
        ),
        code(
            "full = robustness.martingale_ruin(spx, vix, rung1=30, rung2=50)\n"
            "win  = spx.index >= '2016-06-01'\n"
            "windowed = robustness.martingale_ruin(spx[win], vix[win], rung1=30, rung2=50)\n"
            "pd.DataFrame({'full history': full, 'chart window (2016–2026)': windowed})"
        ),

        # ---- BEAT 7 ----------------------------------------------------------
        md(
            "## 7 · Going further\n\n"
            "- **VRP-hedged return** as the dependent variable — does any excess survive once "
            "you strip the variance premium? If not, case closed.\n"
            "- **Term-structure conditioning** (VIX vs VIX3M backwardation at the event).\n"
            "- **Deflated Sharpe** over the full (trigger × horizon × exit) grid, à la Study 02, "
            "for the backtest layer when `backtest.py` lands.\n"
            "- **Cross-asset replication** on MOVE (bonds) and DVOL (crypto).\n\n"
            "Engine: [`../../../quantlab/`](../../../quantlab/). Method: "
            "[`METHODOLOGY.md`](../../../METHODOLOGY.md)."
        ),
    ]
    return new_notebook(cells=cells, metadata=_meta())


def _meta():
    return {
        "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
        "language_info": {"name": "python"},
    }


def main():
    targets = {
        "01_for_the_curious.ipynb": build_curious(),
        "02_for_the_quants.ipynb": build_quants(),
    }
    for fname, nb in targets.items():
        path = os.path.join(HERE, fname)
        with open(path, "w", encoding="utf-8") as fh:
            nbf.write(nb, fh)
        print(f"wrote {fname}  ({len(nb.cells)} cells)")


if __name__ == "__main__":
    main()
