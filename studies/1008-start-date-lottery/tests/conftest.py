"""Shared fixtures for Study 1008 — deterministic, offline, no network.

The synthetic world can hold the *distribution* of returns fixed while
changing only their **order**. That is the whole experiment: a shuffled path has identical
mean, volatility and terminal value for a lump sum, but a completely different outcome for
anyone contributing or withdrawing along the way. Any effect that survives the shuffle is about
the return distribution; any effect that vanishes is sequence risk, by definition.

Both worlds come from the same generator with one knob moved, which is the whole point:
a test that passes on the planted world and *also* passes on the null is not testing
anything.
"""

import os
import sys

import pytest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..")))

from startdate import data  # noqa: E402

N_YEARS = 12
N_ASSETS = 6


@pytest.fixture
def planted():
    """A panel carrying the planted, persistent component (signal_strength=1)."""
    return data.synthetic_panel(n_assets=N_ASSETS, n_years=N_YEARS,
                                signal_strength=1.0, seed=1008)


@pytest.fixture
def null_panel():
    """The matching null: market factor plus idiosyncratic noise only."""
    return data.synthetic_panel(n_assets=N_ASSETS, n_years=N_YEARS,
                                signal_strength=0.0, seed=1008)

