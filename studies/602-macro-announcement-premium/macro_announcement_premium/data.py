# Real tape
# --------------------------------------------------------------------------- #
def fetch_panel(start: str = "1996-12-01", end: str | None = None,
                prices_path: str = PRICES_CACHE, retries: int = 3) -> pd.DataFrame:
    """Download SPY + TLT daily adjusted (total-return) closes and cache them.

    Network-only; used once to build the cache. Never imported by the offline cells.
    """
    import time

    import yfinance as yf

    last_err = None
    for attempt in range(retries):
        try:
            raw = yf.download(["SPY", "TLT"], start=start, end=end, auto_adjust=True,
                              progress=False)["Close"]
            if raw is not None and len(raw) > 0:
                break
        except Exception as e:  # pragma: no cover - network flakiness
            last_err = e
            time.sleep(2 * (attempt + 1))
    else:  # pragma: no cover
        raise RuntimeError(f"yfinance failed after {retries} tries: {last_err}")
    prices = raw.dropna(how="all")
    os.makedirs(os.path.dirname(prices_path), exist_ok=True)
    prices.to_csv(prices_path)
    return prices


def have_real(prices_path: str = PRICES_CACHE) -> bool:
    return os.path.exists(prices_path)


def load_real(path: str = PRICES_CACHE) -> pd.DataFrame:
    """Wide adjusted-close frame (index = date, columns = SPY, TLT)."""
    return pd.read_csv(path, index_col=0, parse_dates=True).sort_index()


# --------------------------------------------------------------------------- #
# Announcement-day masks
# --------------------------------------------------------------------------- #
def _mask_for(index: pd.DatetimeIndex, cal: pd.DatetimeIndex) -> tuple[np.ndarray, int]:
    """Boolean mask over ``index`` tagging each announcement's trading session.

    CPI and NFP land at 08:30 ET (before the open) and the FOMC statement at ~14:00 ET
    (before the close), so the **close-to-close return of the release date itself** is the
    session that prices the news. Announcements on non-trading days (market holidays, e.g.
    an NFP on Good Friday) are mapped to the **next** trading session. Returns the mask
    and the number of announcements that needed forward-mapping.
    """
    mask = np.zeros(len(index), dtype=bool)
    mapped = 0
    lo, hi = index.min(), index.max()
    for d in cal:
        if d < lo or d > hi:
            continue
        pos = index.searchsorted(d, side="left")
        if pos >= len(index):
            continue
        if index[pos] != d:
            mapped += 1
        mask[pos] = True
    return mask, mapped


def announcement_masks(index: pd.DatetimeIndex) -> dict:
    """Per-type + pooled announcement-day masks aligned to a trading-day index.

    Returns ``{"FOMC": m, "CPI": m, "NFP": m, "ANY": m, "n_mapped": k, "n_overlap": j}``
    where ``ANY`` is the union (the pooled Savor-Wilson announcement-day set), ``n_mapped``
    counts announcements moved to the next session (holiday releases) and ``n_overlap``
    counts sessions carrying more than one announcement type (e.g. CPI + FOMC same day).
    """
    cals = calendars()
    out: dict = {}
    mapped = 0
    for name, cal in cals.items():
        m, k = _mask_for(index, cal)
        out[name] = m
        mapped += k
    stack = np.vstack([out["FOMC"], out["CPI"], out["NFP"]])
    out["ANY"] = stack.any(axis=0)
    out["n_overlap"] = int((stack.sum(axis=0) > 1).sum())
    out["n_mapped"] = mapped
    return out


# --------------------------------------------------------------------------- #
# Synthetic positive control
# --------------------------------------------------------------------------- #
def synthetic_world(n_days: int = 7000, edge: float = 0.0, seed: int = 602,
                    sig_daily: float = 0.012, a_frac: float = 0.12
                    ) -> tuple[pd.Series, np.ndarray]:
    """Deterministic daily SPY-like return series + a planted announcement-day mask.

    A random-walk daily return series in which a fixed, evenly-spread ``a_frac`` share of
    days are (synthetic) announcement days; if ``edge`` != 0 those days get an extra mean
    return of ``edge``. With ``edge = 0`` announcement days are statistically identical to
    the rest — the A-vs-rest test must NOT manufacture significance. Decorative business-
    day index (span << 250 years); positions carry the logic.
    """
    rng = np.random.default_rng(seed)
    ret = rng.normal(0.0003, sig_daily, size=n_days)
    step = int(round(1.0 / a_frac))
    mask = np.zeros(n_days, dtype=bool)
    mask[np.arange(0, n_days, step)] = True
    ret[mask] += edge
    idx = pd.bdate_range("2000-01-03", periods=n_days)
    return pd.Series(ret, index=idx, name="ret"), mask
