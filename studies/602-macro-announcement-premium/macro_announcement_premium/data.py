"""Data layer for Study 602 — Macro-Announcement-Day Premium (Savor-Wilson).

Two sources, both offline-friendly once cached:

* **Real tape.** Daily adjusted (total-return) closes for SPY and TLT (yfinance, no key),
  cached under ``_cache/map_prices.csv``. The **scheduled macro-announcement calendar**
  (FOMC decision days + CPI release days + Employment Situation "NFP" release days,
  1997 -> 2026) is hardcoded below with its construction documented per-list. All three
  release schedules are published **in advance** (the Fed publishes meeting dates a year
  ahead; the BLS publishes its release calendar months ahead), so the announcement-day tag
  is knowable before the day — the whole point of Savor-Wilson's framing.

* **Synthetic.** A deterministic, fixed-seed daily world with a *planted* announcement-day
  premium of controllable size (knob ``edge``). It is the positive control: with
  ``edge = 0`` the A-day-vs-rest test must NOT manufacture significance; with a planted
  edge it must light up. A faithful-engine / power check only — never cited in support of
  a real-tape stamp.

Calendar construction (documented, verifiable):

* ``FOMC_DATES`` — scheduled FOMC meeting *decision* dates (statement release days),
  1997 -> 2026-06. Source: Federal Reserve historical FOMC calendars
  (federalreserve.gov/monetarypolicy/fomc_historical_year.htm). Scheduled meetings only —
  no inter-meeting / emergency actions (those are not pre-known, so they cannot carry an
  ex-ante premium). Same table as desk study 517 (pre-FOMC drift), trimmed to 1997+.

* ``CPI_DATES`` — actual CPI news-release dates, 1997-01 -> 2026-06 (353 releases).
  Sources: (a) 1997-2000: the official BLS *Historical Release Dates* table
  (bls.gov/bls/histreleasedates.pdf); (b) mid-1999 -> 2026: the BLS CPI archived-news-
  release index (bls.gov/bls/news-release/cpi.htm), whose archive filenames carry the
  release date (``cpi_MMDDYYYY``). The two sources overlap on 1999-2000 and agree on
  every one of the 19 overlapping dates. Not a "pattern" reconstruction — these are the
  actual release days, including shutdown-delayed ones (e.g. 2013-10-30, 2025-10-24) and
  the missing Oct-2025 release (2025 has 11 releases: the Oct-2025 CPI was never
  published due to the federal shutdown).

* ``NFP_DATES`` — actual Employment Situation news-release dates, 1997-01 -> 2026 (the
  tail of the list carries the published schedule through 2026-12). Same two sources as
  CPI (empsit archive index + histreleasedates.pdf). 344 of 359 are Fridays; every
  non-Friday is a documented exception (July-4th-week Thursdays, the 1998-11-05 early
  release, shutdown-delayed reports 2013-10-22 / 2025-11-20 / 2025-12-16, and 2026
  schedule slips). One known archive-filename quirk corrected: the Dec-1999 report is
  archived as ``empsit_01192000.txt`` but was released 2000-01-07 per the official
  histreleasedates.pdf — we carry the official date.

Announcement days falling on market holidays (e.g. the NFP on Good Friday 1999-04-02) are
mapped to the **next trading session** — the first session that can price the news; the
mapped count is reported by ``announcement_masks``.

Pure numpy + pandas + stdlib offline. ``fetch_panel`` (network) builds the cache once and
is never imported by the notebooks' offline cells.
"""

