"""Shared fixtures for Study 983 — deterministic, offline, no network.

The planted world has a global risk factor that crypto prices continuously and
equities price only when they are open, so the weekend crypto return genuinely contains
Monday's news. The null keeps crypto and equities correlated but gives the weekend no extra
content — the case in which any Monday result is a clock artefact or a fluke.

Both worlds come from the same generator with one knob moved, which is the whole point:
a test that passes on the planted world and *also* passes on the null is not testing
anything.
"""

