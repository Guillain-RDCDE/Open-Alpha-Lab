             "print(f\"hedge (long high-F, short low-F): {s['mean']:+.2%}/yr  Sharpe {s['sharpe']:.2f}  (t~{s['tstat']:.1f})  hit {s['hit_rate']:.0%}\")\n"
             "(h['hedge']*100).plot.bar(color=['#2ea44f' if v>0 else '#c0392b' for v in h['hedge']],\n"
