def build_quants():
    cells = [
        md("# Scorecard — a quantitative teardown 🔬\n### The F-score long-short · the inverted sign · the small-cap-value / crowding explanation\n\n"
           + VERDICT +
           "The deep companion to the [notebook for the curious](01_for_the_curious.ipynb). A celebrated "
           "accounting screen that doesn't survive on the tradable blue-chip universe.\n\n"
           "> ⚠️ **Not investment advice.** Nine SEC EDGAR concepts + Yahoo annual returns, ~237 current "
           "S&P 500 members, XBRL era. Sources in [`docs/references.md`](../docs/references.md)."),
        code(BOOT),
        md("## Verdict, up front\n\n| Axis | Stamp | Why |\n|---|---|---|\n"
           "| Signal | **Weak** | hedge −3.7%/yr, Sharpe −0.39, t −1.7 — inverted |\n"
           "| Tradability | **Mirage** | low-F beat high-F on large caps |\n"
           "| Sorts large-cap winners? | **Not supported** | it's a small-cap value effect |\n\n"
           "> 💡 *In plain words:* a genuine quality screen, measured in the wrong universe."),
        md("## 1 · The claim, steelmanned\n\n- **H₁:** high F-score predicts high forward returns.\n"
           "- **H₂:** the long-high / short-low hedge is positive and significant.\n"
           "- **H₃:** it's tradable on liquid large caps (not just small-cap value)."),
        md("## 2 · So what? — what rides on each\n\nH₁/H₂ would make the F-score a free, transparent "
           "quality factor straight from 10-Ks. H₃ decides whether it survives where you can trade in "
           "size. A small-cap-value-only effect is real science but useless to a large-cap book."),
        md("## 3 · How we'd know — the protocol\n\nNine EDGAR concepts → the 0–9 F-score → annual tercile "
           "sort → long top (healthy), short bottom (weak) → next-year hedge, Sharpe, t-stat, hit rate "
           "over the XBRL window."),
        md("## 4 · The teardown"),
        md("### 4.1 The long-short, year by year"),
        code("disp=h.copy(); disp.columns=['high-F leg','low-F leg','hedge (high-low)']\n"
             "display((disp*100).round(1))\n"
             "s=st.summary(h['hedge']); print({k:round(v,3) for k,v in s.items()})"),
        md("> 💡 *In plain words:* the hedge mean is **negative** (−3.7%/yr) and wins only ~33% of years. "
           "**H₁ and H₂ are rejected on this universe** — the sign is backwards."),
        md("### 4.2 Why it doesn't replicate — H₃ fails"),
        md("Four forces flatten and flip it on large caps:\n\n"
           "1. **It's a small-cap value effect.** Piotroski (2000) built the F-score *within* high "
           "book-to-market firms — small, neglected, distressed. That's where the spread lives.\n"
           "2. **High-F is crowded.** On heavily-covered large caps a strong balance sheet is already in "
           "the price — no neglect premium left.\n"
           "3. **Low-F snaps back.** Beaten-down large-cap cyclicals / troughing growth rebound, so the "
           "*short* leg wins.\n"
           "4. **Survivorship.** Current members exclude the low-F firms that actually went bankrupt — the "
           "ones the short was meant to catch. **H₃ rejected.**"),
        md("## 5 · The verdict\n\nH₁/H₂/H₃ all rejected on tradable large caps → Signal `WEAK` "
           "(inverted), Tradability `MIRAGE`, sorts-large-cap-winners `NOT SUPPORTED`. The fingerprinted "
           "run is in [`docs/results.md`](../docs/results.md)."),
        md("## 6 · Could you trade it?\n\nNot on this universe. To harvest the F-score premium you'd run "
           "it on a small-cap, high-book-to-market book — illiquid, under-covered names where a clean "
           "scorecard is a genuine surprise. Outside what a free EDGAR pull on current S&P members offers."),
        md("## 7 · Going further\n\nForks: (a) the F-score *within* a value screen (its native habitat); "
           "(b) a Russell 2000 universe; (c) the F-score *change* vs level; (d) combine with accruals "
           "([52](../../52-smoke-screen/)) into a composite quality factor. Backlog: "
           "[`docs/pwb_strategies_inventory.md`](../../../docs/pwb_strategies_inventory.md)."),
    ]
    _write(new_notebook(cells=cells, metadata=_meta()), "02_for_the_quants.ipynb")


