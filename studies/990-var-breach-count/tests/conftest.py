"""Shared fixtures for Study 990 — deterministic, offline, no network.

The planted world generates returns from a distribution whose true quantiles are
known exactly, so a VaR model can be graded against the truth rather than against another
model. The knobs control fat tails and volatility clustering independently, which is how the
study separates "the model's distribution is wrong" from "the model's conditioning is wrong" —
two failures that look identical in a breach count.

Both worlds come from the same generator with one knob moved, which is the whole point:
a test that passes on the planted world and *also* passes on the null is not testing
anything.
"""

