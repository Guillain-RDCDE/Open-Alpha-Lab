"""Worked extension run (beat 7) — the no-borrowing test on real SPY/QQQ.

The headline study flags one honest caveat: the overlay must take leverage in calm regimes, so the
gain is `RISK-MANAGED`, not free. The Cederburg et al. (2020) critique sharpens it — a Sharpe gain
that *needs* leverage may not be an investor gain. So we split the edge by capping leverage:

    * cap = 1.0  -> de-risk only (no borrowing): cut exposure in storms, never gear up.
    * cap = high -> the unconstrained Moreira-Muir overlay.

`gain_full = gain_derisk + gain_leverage` isolates the contested leverage slice. This writes a
reproducible docs/extension.md.

    # uses the same cached daily closes as verify.py; --fetch to populate on a miss
    ../../.venv/Scripts/python.exe examples/extension.py
"""

import argparse
import os
import sys

_STUDY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _STUDY)
sys.path.insert(0, os.path.abspath(os.path.join(_STUDY, "..", "..")))

from storm_shy import data, vol, extension
from quantlab.repro import DEFAULT_AS_OF, as_of, fingerprint

OUT = os.path.join(_STUDY, "docs", "extension.md")
TICKERS = ["SPY", "QQQ"]
COST_BPS = 1.0


def load(ticker, fetch):
    close = data.fetch_prices(ticker, fetch=fetch)
    if close.empty:
        return close
    return as_of(close.to_frame(), DEFAULT_AS_OF)["close"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fetch", action="store_true", help="populate the close cache (network)")
    args = ap.parse_args()

    results, fps = {}, {}
    for tk in TICKERS:
        close = load(tk, args.fetch)
        if close.empty:
            print(f"[skip] {tk}: no cache (run with --fetch)"); continue
        r = vol.to_returns(close)
        results[tk] = {
            "n_bars": len(r),
            "decomp": extension.gain_decomposition(r, cost_bps=COST_BPS),
            "sweep": extension.leverage_cap_sweep(r, cost_bps=COST_BPS),
        }
        fps[tk] = (fingerprint(close.to_frame()), close.index.min().date(), close.index.max().date())
        g = results[tk]["decomp"]
        print(f"\n=== {tk} ({results[tk]['n_bars']} bars) ===")
        print(f"  Sharpe gain: de-risk (no borrow) {g['gain_derisk']:+.2f} + leverage "
              f"{g['gain_leverage']:+.2f} = full {g['gain_full']:+.2f}  "
              f"(de-risk = {g['share_derisk']:.0%} of the edge)")
        print(f"  no-borrow: avg leverage {g['derisk_avg_leverage']:.2f}, drawdown "
              f"{g['buyhold_maxdd']:.0%} -> {g['derisk_maxdd']:.0%}, CE gain {g['ce_gain_derisk_pct']:+.2f}%/yr")

    if results:
        _write(OUT, results, fps)
        print(f"\nwrote {OUT}")
    else:
        print("\ncache is empty -- run with --fetch to populate the closes first.")


def _write(path, results, fps):
    decs = [(tk, r["decomp"]) for tk, r in results.items()]
    n = len(decs)
    survive = sum(1 for _, g in decs if g["gain_derisk"] > 0 and g["share_derisk"] > 0.5)

    lines = [f"""# Extension (beat 7) — the no-borrowing test: what survives a leverage cap of 1.0?

*Generated by [`examples/extension.py`](../examples/extension.py). The headline study's one caveat is
**leverage**: the overlay gears up in calm regimes to hold its risk target, so the gain is
`RISK-MANAGED`, not free — and the Cederburg et al. (2020) critique is that a Sharpe gain needing
leverage may not be an investor gain. We make it a backtest by splitting the edge with a leverage
cap: **de-risk only** (cap 1.0 — cut exposure in storms, never borrow) vs the **unconstrained**
overlay, so ``gain_full = gain_derisk + gain_leverage`` isolates the contested leverage slice. Real
SPY/QQQ daily total-return closes, {COST_BPS:.0f} bp/turn, as-of **{DEFAULT_AS_OF}**; match the
fingerprints below.*

## Data stamp
"""]
    for tk, (fp, lo, hi) in fps.items():
        lines.append(f"- **{tk}**: {lo} → {hi}, fingerprint `{fp}`")

    for tk, r in results.items():
        g = r["decomp"]
        lines.append(f"""
## {tk} — de-risk vs leverage slice ({r['n_bars']} bars)

| slice | Sharpe gain | needs borrowing? |
|---|---|---|
| **de-risk** (cap 1.0) | **{g['gain_derisk']:+.2f}** | no — avg leverage {g['derisk_avg_leverage']:.2f} |
| leverage (calm gearing) | {g['gain_leverage']:+.2f} | yes |
| **full overlay** | {g['gain_full']:+.2f} | — |

- **De-risk carries {g['share_derisk']:.0%} of the edge** — and it needs **no borrowing**. The
  drawdown reduction is almost entirely here: **{g['buyhold_maxdd']:.0%} → {g['derisk_maxdd']:.0%}**
  with leverage capped at 1.0, and a no-borrow CRRA certainty-equivalent gain of
  **{g['ce_gain_derisk_pct']:+.2f}%/yr**.
- **The leverage slice is {g['gain_leverage']:+.2f}** — the contested Cederburg piece. On the real
  tape it is small (the fat-tailed, vol-asymmetric market rewards *cutting* risk in storms far more
  than *adding* it in calm), so almost none of the edge is levered into existence.

### Leverage-cap sweep

| max leverage | Sharpe gain | managed Sharpe | avg leverage | % days capped | managed maxDD |
|---|---|---|---|---|---|""")
        for cap, row in r["sweep"].iterrows():
            lines.append(
                f"| {cap:.2f} | {row['sharpe_gain']:+.2f} | {row['managed_sharpe']:+.2f} | "
                f"{row['avg_leverage']:.2f} | {row['frac_capped']:.0%} | {row['managed_maxdd']:.0%} |")
        lines.append("")

    lines.append(f"""
## What it shows

The one caveat the headline verdict flags — *it needs leverage* — turns out, on the real tape, to be
the part that matters **least**. The Sharpe gain and essentially all of the drawdown reduction
survive a hard **no-borrowing** constraint in **{survive}/{n}** tapes, because the edge is
overwhelmingly **storm-dodging** (de-risk), not calm-gearing (leverage). A long-only, leverage-capped,
financing-constrained book — the exact investor the Cederburg critique worries about — **keeps the
benefit**. The framework's hardest constraint, imposed, leaves `Tradability INVESTABLE` standing and
sharpens the `RISK-MANAGED` stamp: the risk being managed is downside, and managing it down requires
no borrowing at all.
""")

    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
