"""The reproducible run behind Study 09's verdict — on the seed-fixed simulator.

Per the desk decision for this study, the verdict basis is a transparent simulator, not a
cached data dump (Avellaneda-Stoikov is a theorem about a model world; the cleanest
falsification builds the world). This script runs the full teardown and writes a reproducible
results doc with a content fingerprint of the simulated inputs, so a re-run that matches the
fingerprint holds the exact same numbers.

    python examples/run_experiments.py

The empirical leg — does *real* crypto order flow have heavy-tailed reach (World B) rather
than exponential (World A)? — is a separate, runnable harness in ``examples/verify_real.py``
(see beat 7). The literature already answers it (power-law trade size / order flow; Gabaix
et al. 2003, Bouchaud et al. 2009), which is why World B is the realistic one.
"""

import os
import sys

import numpy as np
import pandas as pd

_STUDY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _STUDY)
sys.path.insert(0, os.path.abspath(os.path.join(_STUDY, "..", "..")))

from phantom_kernel import experiments as ex, sim
from quantlab.repro import fingerprint

pd.set_option("display.width", 220)
pd.set_option("display.max_columns", 20)
pd.set_option("display.float_format", lambda v: f"{v:,.4f}")

OUT = os.path.join(_STUDY, "docs", "results.md")
SEED = 0


def _sim_fingerprint() -> str:
    """A content hash of the simulated kernel inputs (so a re-run can verify byte-equality)."""
    deltas = ex.default_deltas()
    ca = sim.fill_counts(sim.WORLD_A, deltas, n_orders=400_000, seed=SEED)
    cb = sim.fill_counts(sim.WORLD_B, deltas, n_orders=400_000, seed=SEED)
    cs = sim.fill_counts(sim.WORLD_B_STRESS, deltas, n_orders=400_000, seed=SEED)
    idx = pd.bdate_range("2000-01-03", periods=len(deltas))
    df = pd.DataFrame({"delta": deltas, "counts_A": ca, "counts_B": cb,
                       "counts_B_stress": cs}, index=idx)
    return fingerprint(df, round_dp=4)


def main():
    rec = ex.estimator_recovery(seed=SEED)
    gof = ex.kernel_gof_table(seed=SEED)
    kins = ex.k_instability(seed=SEED)
    tA = ex.tournament(sim.WORLD_A, seed=SEED)
    tB = ex.tournament(sim.WORLD_B, seed=SEED)
    msA = ex.tournament_multiseed(sim.WORLD_A)
    msB = ex.tournament_multiseed(sim.WORLD_B)
    abl = ex.k_ablation(sim.WORLD_B)
    fp = _sim_fingerprint()

    print(f"sim fingerprint: {fp}")
    print("\n[estimator recovery, World A]", rec)
    print("\n[kernel goodness-of-fit]\n", gof.to_string())
    print("\n[static-k spread error]")
    for k in ("k_true", "k_recovered_per_regime", "k_pooled_static",
              "spread_pct_error_per_regime", "max_abs_spread_pct_error", "bound_T1"):
        print(f"  {k}: {kins[k]}")
    print("\n[tournament World A]  k_as=%.3f half=%.3f\n" % (tA.attrs["k_as"], tA.attrs["half_spread"]), tA.to_string())
    print("\n[tournament World B]  k_as=%.3f half=%.3f\n" % (tB.attrs["k_as"], tB.attrs["half_spread"]), tB.to_string())
    print("\n[k-ablation, World B]  k_fit=%.4f\n" % abl.attrs["k_fit"], abl.to_string())

    _write(OUT, rec, gof, kins, tA, tB, msA, msB, abl, fp)
    print(f"\nwrote {OUT}")


