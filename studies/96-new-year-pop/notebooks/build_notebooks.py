            "ax.axhline(0, color='k', lw=.8); ax.set_ylabel('Jan small - large (%)')\n"
            "ax.set_title(f'Small beats large in {wins}/{n} Januaries ({wins/n*100:.0f}%) -- Wilson95 [{lo*100:.0f}%, {hi*100:.0f}%]')\n"
