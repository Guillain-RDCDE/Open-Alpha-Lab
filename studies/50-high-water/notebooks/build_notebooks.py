from __future__ import annotations

import os

import nbformat as nbf
from nbformat.v4 import new_code_cell, new_markdown_cell, new_notebook

HERE = os.path.dirname(os.path.abspath(__file__))

BOOT = """\
import sys, os
sys.path.insert(0, os.path.abspath("../../.."))  # repo root (quantlab/)
sys.path.insert(0, os.path.abspath(".."))        # study package (high_water/)
%matplotlib inline
import matplotlib.pyplot as plt
plt.rcParams["figure.figsize"] = (10, 5.5); plt.rcParams["axes.grid"] = True
import numpy as np, pandas as pd
from high_water import data, strategy as st
ret = data.fetch_panel()                       # cache-first; built by examples/verify.py --fetch
hi = st.cross_section_hedge(ret, st.nearness(ret))
mo = st.cross_section_hedge(ret, st.momentum(ret))
"""

VERDICT = (
    "![Signal: None](https://img.shields.io/badge/Signal-None-c0392b?style=flat-square)\n"
    "![Tradability: Mirage](https://img.shields.io/badge/Tradability-Mirage-c0392b?style=flat-square)\n"
    "![A distinct anomaly?: Busted](https://img.shields.io/badge/A_distinct_anomaly%3F-Busted-8b949e?style=flat-square)\n\n"
)


def md(t):
    return new_markdown_cell(t)


def code(t):
    return new_code_cell(t)


def build_curious():
    cells = [
        md("# High-Water 🏔️\n### \"Buy stocks near their 52-week high\" — a distinct edge, or just momentum?\n\n"
           + VERDICT +
           "There's a famous idea that stocks trading near their one-year high keep climbing — an "
           "*anchoring* story said to be different from plain momentum. We test both halves on large-cap "
           "stocks: it didn't pay (the long-short *lost*), and it turns out to be 0.87 correlated with "
           "ordinary momentum — the same factor with a behavioural label.\n\n"
           "> 📓 **Plain-language layer.** The correlation and the t-stats are in "
           "**[02_for_the_quants.ipynb](02_for_the_quants.ipynb)**.\n>\n"
           "> ⚠️ **Not investment advice.** Every chart is generated by the code beside it."),
        code(BOOT),
        md("## The answer first 🎯\n\n"
           "| The claim | The data (2000–2026, large caps) |\n|---|---|\n"
           "| \"Near-high stocks out-earn\" | The long-short earns **−8.4%/yr** (Sharpe −0.40) — it *lost*. |\n"
           "| \"It's distinct from momentum\" | It's **0.87 correlated** with the momentum hedge. |\n"
           "| \"A free anchoring edge\" | Negative gross, so costs only deepen the hole. |"),
        md("## 1 · The claim\n\nGeorge & Hwang (2004): a stock's **nearness to its 52-week high** (price ÷ "
           "one-year high) predicts its return — investors anchor on the high and underreact — and this "
           "beats, and is *separate from*, Jegadeesh-Titman momentum."),
        md("## 2 · So what?\n\nIf it's a distinct, durable edge, it's another factor for the toolbox. If "
           "it's momentum relabelled — and momentum that didn't even pay on large caps — then it's a "
           "story dressed as a discovery."),
        md("## 3 · How would we even know?\n\nBuild the nearness long-short, measure its return and "
           "t-stat, then **correlate it with a plain 12-month-momentum long-short**. High correlation "
           "means same factor; a negative return means no premium to begin with."),
        code("h,m=st.stats(hi),st.stats(mo)\n"
             "fig,ax=plt.subplots(figsize=(7,4))\n"
             "ax.bar(['52-week-high\\nnearness','12-month\\nmomentum'],[h['mean_ann']*100,m['mean_ann']*100],color=['#c0392b','#8b949e'])\n"
             "ax.set_ylabel('long-short return (%/yr)'); ax.axhline(0,color='k',lw=.8)\n"
             "ax.set_title(f\"Both negative on large caps; and they're {st.signal_overlap(ret):.2f} correlated\"); plt.show()"),
        md("## 4 · The teardown\n\nThe two hedges move together — because they *are* the same bet. And "
           "near-high names got punished in the 2000 and 2008 rebounds."),
        code("eqH=(1+hi).cumprod(); eqM=(1+mo).cumprod()\n"
             "ax=eqH.plot(label='52-week-high nearness',lw=1.8); eqM.plot(ax=ax,label='12-month momentum',lw=1.4,alpha=.8)\n"
             "ax.set_title('Growth of $1 in the long-short, 2000-2026 (they track each other)'); ax.legend(); plt.show()\n"
             "print(f\"correlation of the two hedges: {st.signal_overlap(ret):+.2f}\")"),
        md("**Read it plainly.** Two lines on top of each other, both heading down. The 52-week-high signal "
           "isn't a new edge — it's momentum, and momentum didn't pay on this universe."),
        md("## 5 · The verdict\n\n**Signal: None** — the long-short lost (significantly). **Tradability: "
           "Mirage** — negative gross. **A distinct anomaly?: Busted** — 0.87 correlated with momentum."),
        md("## 6 · Could you actually trade it?\n\nThere's nothing to trade: the gross hedge is negative, "
           "and to the extent it captures anything, it's the momentum factor you could get more cleanly "
           "(and which also struggled here — see [Study 24 Stampede](../../24-stampede/))."),
        md("## 7 · Going further 🚪\n\nThe quants notebook shows the 0.87 correlation and the decay. This "
           "closes the second five-study bench (46–50). The negative sign ties to "
           "[Study 33 Slingshot](../../33-slingshot/) — reversal on the S&P cross-section."),
    ]
    _write(new_notebook(cells=cells, metadata=_meta()), "01_for_the_curious.ipynb")


def build_quants():
    cells = [
        md("# High-Water — a quantitative teardown 🔬\n### The nearness hedge with a Lo t-stat · the 0.87 correlation to momentum · decay · costs\n\n"
           + VERDICT +
           "The deep companion to the [notebook for the curious](01_for_the_curious.ipynb). We test "
           "whether the 52-week-high effect pays and whether it's distinct from momentum.\n\n"
           "> ⚠️ **Not investment advice.** 398 S&P 500 names with ≥20y history (Yahoo), 2000–2026; "
           "survivorship-biased, large-cap. Sources in [`docs/references.md`](../docs/references.md)."),
        code(BOOT),
        md("## Verdict, up front\n\n| Axis | Stamp | Why |\n|---|---|---|\n"
           "| Signal | **None** | nearness hedge −8.4%/yr, Sharpe −0.40, t −2.2 |\n"
           "| Tradability | **Mirage** | negative gross; costs deepen it |\n"
           "| Distinct anomaly? | **Busted** | 0.87 correlated with momentum |\n\n"
           "> 💡 *In plain words:* momentum relabelled, and momentum that lost here."),
        md("## 1 · The claim, steelmanned\n\n- **H₁:** the nearness long-short earns a significant "
           "positive premium.\n- **H₂:** it is distinct from 12-month momentum (low correlation).\n"
           "- **H₃:** it's stable over time."),
        md("## 2 · So what? — what rides on each\n\nIf H₁/H₂ hold, it's a new tradable factor. If H₂ "
           "fails, it's momentum with a story; if H₁ fails too, there's no premium at all."),
        md("## 3 · How we'd know — the protocol\n\nNearness long-short + Lo t-stat → correlation with the "
           "momentum hedge → decade split → cost sweep."),
        md("## 4 · The teardown"),
        md("### 4.1 The nearness hedge vs the momentum control"),
        code("display(pd.DataFrame({'52-week-high':st.stats(hi),'12m momentum':st.stats(mo)}).T[['mean_ann','sharpe','tstat','hit_rate','n']].round(3))\n"
             "print(f\"corr(nearness hedge, momentum hedge) = {st.signal_overlap(ret):+.2f}\")"),
        md("> 💡 *In plain words:* nearness loses (t −2.2) and is 0.87 correlated with momentum. "
           "**H₁ and H₂ both rejected.**"),
        md("### 4.2 Decay"),
        code("for lab,sl in [('1999-2012',hi.loc[:'2012']),('2013-on',hi.loc['2013':])]:\n"
             "    print(f'{lab}: Sharpe {st.stats(sl)[\"sharpe\"]:+.2f}, mean {st.stats(sl)[\"mean_ann\"]:+.2%}/yr')"),
        md("> 💡 *In plain words:* strongly negative early (momentum crashes of 2000/2008), drifting to "
           "zero. **H₃** — no stable positive regime."),
        md("### 4.3 Cost sweep — a negative book only gets worse"),
        code("rows={'gross':st.stats(hi)['sharpe']}\n"
             "for c in (5,10,20): rows[f'{c}bp']=st.stats(st.net_of_cost(hi,c))['sharpe']\n"
             "display(pd.Series(rows, name='net Sharpe').round(3))"),
        md("> 💡 *In plain words:* since gross is negative, turnover just compounds the loss."),
        md("## 5 · The verdict\n\nH₁, H₂, H₃ all rejected → Signal `NONE`, Tradability `MIRAGE`, "
           "distinct-anomaly claim `BUSTED`."),
        md("## 6 · Could you trade it?\n\nNo — and if you wanted the momentum exposure it proxies, you'd "
           "use momentum directly (cleaner, and itself fragile on large caps — Study 24 Stampede). The "
           "52-week-high label adds a narrative, not an edge."),
        md("## 7 · Going further\n\nForks: (a) a point-in-time / small-cap universe (George-Hwang's effect "
           "is stronger in smaller names, the untradable end); (b) double-sort nearness × momentum to "
           "confirm there's no residual; (c) the momentum-crash overlay (Daniel-Moskowitz 2016) on the "
           "near-high book. Backlog: [`docs/pwb_strategies_inventory.md`](../../../docs/pwb_strategies_inventory.md)."),
    ]
    _write(new_notebook(cells=cells, metadata=_meta()), "02_for_the_quants.ipynb")


def _meta():
    return {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"}}


def _write(nb, name):
    path = os.path.join(HERE, name)
    with open(path, "w", encoding="utf-8") as f:
        nbf.write(nb, f)
    print("wrote", path)


if __name__ == "__main__":
    build_curious()
    build_quants()
