def md(t):
    return new_markdown_cell(t)


def code(t):
    return new_code_cell(t)


def build_curious():
    cells = [
        md("# Paper-Moon 🌙\n### The Fed Model: a famous timing rule built on a logical bug\n\n"
           + VERDICT +
           "\"Stocks are cheap when their earnings yield beats the 10-year Treasury yield.\" It sounds "
           "obvious, it has a Fed-sounding name, and it's quoted constantly. Over 125 years it times the "
           "market no better than buying and holding — and its key idea, comparing stocks to bonds, turns "
           "out to add *nothing detectable*. It's only a paper moon.\n\n"
           "> 📓 **Plain-language layer.** The forecasting horse-race and the inflation illusion are in "
           "**[02_for_the_quants.ipynb](02_for_the_quants.ipynb)**.\n>\n"
           "> ⚠️ **Not investment advice.** Every chart is generated by the code beside it."),
        code(BOOT),
        md("## The answer first 🎯\n\n"
           "| The pitch | The catch |\n|---|---|\n"
           "| \"Time the market with E/P vs bond yields\" | It matches buy-and-hold's Sharpe and **loses** a point of return. |\n"
           "| \"The bond comparison is the insight\" | **E/P alone forecasts at least as well** — the gap is inside overlap-corrected noise. |\n"
           "| \"A sound valuation model\" | It confuses a *real* earnings yield with a *nominal* bond yield. |"),
        md("## 1 · The claim\n\nThe Fed Model: hold equities when the S&P earnings yield (E/P) is above "
           "the 10-year Treasury yield (stocks 'cheap' relative to bonds), and step into bonds when it's "
           "below. A market-timing rule taught in every CFA prep book."),
        md("## 2 · So what?\n\nIf comparing equity and bond yields times the market, it's a simple, "
           "powerful asset-allocation switch. If the comparison is a conceptual error, then a generation "
           "of strategists has been anchoring on a number that means less than it seems."),
        md("## 3 · How would we even know?\n\nRun the timing on 125 years of Shiller data against "
           "buy-and-hold; then the decisive test — does the **Fed signal (E/P − yield)** forecast future "
           "returns better than **E/P alone**? If not, the bond term is dead weight. One honesty rule: "
           "12-month forward returns overlap massively, so ~1,500 monthly rows are really ~125 independent "
           "observations — the error bars below come from a block bootstrap that respects that."),
        code("rows={'Fed-model timing':st.summary(timing),'Buy & hold S&P':st.summary(bh)}\n"
             "t=pd.DataFrame(rows).T[['cagr','sharpe','max_drawdown']]\n"
             "display(t.style.format({'cagr':'{:.1%}','sharpe':'{:.2f}','max_drawdown':'{:.0%}'}))\n"
             "eqT=(1+timing).cumprod(); eqB=(1+bh).cumprod()\n"
             "ax=eqB.plot(label='Buy & hold S&P',lw=1.4); eqT.plot(ax=ax,label='Fed-model timing',lw=1.4)\n"
             "ax.set_yscale('log'); ax.set_title('Growth of $1, 1900-2026'); ax.legend(); plt.show()"),
        md("## 4 · The teardown — does the bond comparison help?\n\nThis is the whole study in one chart: "
           "the Fed signal vs E/P alone as forecasters of the next year's return."),
        code("race=st.predictive_corr_race(d['ep'],sig,d['tr'])  # overlap-corrected block-bootstrap SEs\n"
             "fig,ax=plt.subplots(figsize=(7,4))\n"
             "ax.bar(['Fed signal\\n(E/P − bond yield)','E/P alone'],[race['corr2'],race['corr1']],\n"
             "       yerr=[race['se2'],race['se1']],capsize=6,color=['#c0392b','#2ea44f'])\n"
             "ax.set_ylabel('corr with next-12m equity return'); ax.set_title('The bond-yield term adds nothing detectable'); plt.show()\n"
             "print(f\"Fed signal {race['corr2']:+.2f} ± {race['se2']:.2f}   vs   E/P alone {race['corr1']:+.2f} ± {race['se1']:.2f}\")\n"
             "print(f\"difference (E/P − Fed) {race['diff']:+.2f} ± {race['se_diff']:.2f}, 95% CI [{race['diff_lo']:+.2f}, {race['diff_hi']:+.2f}]\")\n"
             "print(f\"({race['n']} overlapping monthly obs ≈ {race['n_indep']} independent ones)\")"),
        md("**Read it plainly.** E/P by itself forecasts at least as well as the famous comparison — and "
           "once the error bars respect the overlap (~125 independent year-length observations, not "
           "1,505 monthly rows), the gap (+0.03 ± 0.05) is pure noise. Subtracting the bond yield adds "
           "nothing detectable: the model's signature ingredient is decoration."),
        md("## 5 · The verdict\n\n**Signal: Weak** — only plain valuation (E/P) carries anything. "
           "**Tradability: Mirage** — buy-and-hold with worse return. **Logic holds?: Busted** — the bond "
           "comparison is inert and rests on a money illusion."),
        md("## 6 · Could you actually trade it?\n\nYou could, but you'd underperform buy-and-hold over a "
           "century while taking on switching risk. If you want the valuation signal, use E/P (or CAPE) "
           "directly — and skip the bond-yield comparison that gives the model its name and its flaw."),
        md("## 7 · Going further 🚪\n\nThe quants notebook shows *why* the comparison fails — E/P tracks "
           "inflation, not the bond yield (Asness 2003, *Fight the Fed Model*). Next: "
           "[Study 48 Groundhog](../../48-groundhog/) — return seasonality, a genuinely strange claim about "
           "stocks repeating their calendar-month performance."),
    ]
    _write(new_notebook(cells=cells, metadata=_meta()), "01_for_the_curious.ipynb")


def build_quants():
    cells = [
        md("# Paper-Moon — a quantitative teardown 🔬\n### Timing vs buy-and-hold · the Fed-signal-vs-E/P horse race · the inflation illusion\n\n"
           + VERDICT +
           "The deep companion to the [notebook for the curious](01_for_the_curious.ipynb). We test the "
           "Fed Model on 125 years and isolate why its bond-yield comparison fails.\n\n"
           "> ⚠️ **Not investment advice.** Shiller monthly S&P series (datahub mirror), 1900–2026. "
           "Sources in [`docs/references.md`](../docs/references.md)."),
        code(BOOT + "\n"),
        md("## Verdict, up front\n\n| Axis | Stamp | Why |\n|---|---|---|\n"
           "| Signal | **Weak** | timing Sharpe 0.72 ≈ buy-and-hold 0.73, lower CAGR |\n"
           "| Tradability | **Mirage** | matches B&H Sharpe & −81% DD, less return |\n"
           "| Logic holds? | **Busted** | the bond term adds nothing detectable (+0.03 ± 0.05 overlap-corrected) and rests on a money illusion |\n\n"
           "> 💡 *In plain words:* the model's signature idea adds nothing the data can detect — and the "
           "premise behind it is a real-vs-nominal confusion."),
        md("## 1 · The claim, steelmanned\n\n- **H₁:** the timing beats buy-and-hold (Sharpe / drawdown).\n"
           "- **H₂ (the model's essence):** E/P − bond yield forecasts returns better than E/P alone.\n"
           "- **H₃:** the comparison reflects a real relationship (E/P tracks the bond yield)."),
        md("## 2 · So what? — what rides on each\n\nIf H₂/H₃ hold, the bond comparison is the insight. If "
           "they fail, the Fed Model is plain valuation plus a conceptual error with a famous name."),
        md("## 3 · How we'd know — the protocol\n\nTiming vs buy-and-hold over 1900–2026 → predictive-corr "
           "horse race (Fed signal vs E/P alone), scored with **overlap-corrected standard errors** — "
           "12-month forward returns share 11 of 12 months with their neighbours, so ~1,505 monthly rows "
           "carry only ~125 independent observations and naive SEs would be ~3.5× too small; we use a "
           "seeded 12-month circular block bootstrap → the Asness money-illusion correlations (E/P vs "
           "yield, E/P vs inflation).\n\n"
           "Two stated limits, both flattering the model that loses anyway: Shiller's monthly earnings are "
           "interpolated quarterly figures published with a lag, so the \"no look-ahead\" in the lagged "
           "signal is only partial; and the bond leg is `y10/12` — a zero-duration cash-like proxy that "
           "spares the timing rule real duration losses."),
        md("## 4 · The teardown"),
        md("### 4.1 Timing vs buy-and-hold"),
        code("display(pd.DataFrame({'Fed-model timing':st.summary(timing),'Buy & hold':st.summary(bh)}).T[['cagr','sharpe','vol_ann','max_drawdown']].round(3))\n"
             "print('time in stocks:', f\"{st.time_in_stocks(sig.reindex(d.index)):.0%}\")"),
        md("> 💡 *In plain words:* equal Sharpe, equal −81% drawdown, less return. **H₁ rejected** — no timing benefit."),
        md("### 4.2 The horse race: Fed signal vs E/P alone"),
        code("race=st.predictive_corr_race(d['ep'],sig,d['tr'])  # seeded 12-month circular block bootstrap\n"
             "print(f\"Fed signal (E/P − y10): corr with next-12m return = {race['corr2']:+.2f}  (block-bootstrap SE {race['se2']:.2f})\")\n"
             "print(f\"E/P alone:              corr with next-12m return = {race['corr1']:+.2f}  (block-bootstrap SE {race['se1']:.2f})\")\n"
             "print(f\"difference (E/P − Fed): {race['diff']:+.2f}  SE {race['se_diff']:.2f}, 95% CI [{race['diff_lo']:+.2f}, {race['diff_hi']:+.2f}]\")\n"
             "print(f\"({race['n']} overlapping monthly obs ≈ {race['n_indep']} independent ones)\")"),
        md("> 💡 *In plain words:* the comparison's point estimate is *lower* than plain E/P's, but the "
           "gap (+0.03 ± 0.05, 95% CI spanning zero) is inside overlap-corrected noise. A century of data "
           "finds **no detectable contribution** from subtracting the bond yield — that is what "
           "\"decoration\" means, and it is all the horse race is entitled to say. "
           "**H₂ rejected** — the model's defining ingredient is inert."),
        md("### 4.3 The money illusion (Asness 2003)"),
        code("print(f\"corr(E/P, 10y yield)        = {d['ep'].corr(d['y10']):+.2f}   (the model assumes ≈1)\")\n"
             "print(f\"corr(E/P, trailing inflation) = {d['ep'].corr(d['infl']):+.2f}   (what E/P really tracks)\")\n"
             "fig,ax=plt.subplots(figsize=(7,4))\n"
             "ax.bar(['vs 10y yield\\n(model assumes)','vs inflation\\n(reality)'],[d['ep'].corr(d['y10']),d['ep'].corr(d['infl'])],color=['#8b949e','#c0392b'])\n"
             "ax.set_ylabel('correlation with E/P'); ax.set_title('E/P tracks inflation, not the bond yield'); plt.show()"),
        md("> 💡 *In plain words:* the earnings yield is a **real** quantity that moves with inflation; the "
           "bond yield is **nominal**. Equating them (Modigliani-Cohn / Asness inflation illusion) is the "
           "model's foundational error. **H₃ rejected.**"),
        md("## 5 · The verdict\n\nH₁, H₂, H₃ all rejected → Signal `WEAK` (only E/P matters), Tradability "
           "`MIRAGE`, model logic `BUSTED`. The `BUSTED` stands on the conceptual error of H₃ — equating a "
           "real earnings yield with a nominal bond yield — not on the (noisy) horse race, which can only "
           "say the bond term adds nothing detectable."),
        md("## 6 · Could you trade it?\n\nUse E/P or CAPE directly for a mild long-horizon valuation tilt; "
           "do not subtract the bond yield. The Fed Model adds a name and a bug, not an edge."),
        md("## 7 · Going further\n\nForks: (a) forward (analyst) earnings yield instead of trailing — the "
           "original Fed-report version; (b) real bond yields (TIPS) instead of nominal — does fixing the "
           "illusion revive the comparison? (c) CAPE-based timing as the honest valuation benchmark. "
           "Backlog: [`docs/pwb_strategies_inventory.md`](../../../docs/pwb_strategies_inventory.md)."),
    ]
    _write(new_notebook(cells=cells, metadata=_meta()), "02_for_the_quants.ipynb")


def _meta():
    return {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"}}


def _write(nb, name):
    path = os.path.join(HERE, name)
    with open(path, "w", encoding="utf-8") as f:
        nbf.write(nb, f)
    print("wrote", path)


