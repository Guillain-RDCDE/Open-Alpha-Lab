            "[`../docs/results.md`](../docs/results.md).\n\n"
            "### 7b · Other forks\n"
            "- **Constrained optimization** (gross/turnover/position limits) — the real-desk fix for "
            "`C⁻¹` instability; does it beat naive net of cost?\n"
