            "`w ∝ C⁻¹E` on a residual-reversion signal. We prove the engine on a synthetic mean-reverting "
            "panel, then show on the real S&P 500 that inverting an estimated covariance is "
            "error-maximization.\n\n"
            "> ⚠️ **Not investment advice.** The core executes on synthetic data; the real run is in "
            "[`../docs/results.md`](../docs/results.md), sources in "
