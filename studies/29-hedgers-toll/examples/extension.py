"""Beat-7 worked complement on the real tape — robustness of the (absent) premium.

If hedging pressure paid, it would pay across signal windows and the long leg (paid speculator) would
carry it. We sweep the normalisation window and split long-only vs long-short on the real tape, writing
`docs/extension.md`.

    python examples/extension.py            # cache-only
    python examples/extension.py --fetch
"""

import argparse
import os
import sys

import pandas as pd

_STUDY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _STUDY)
sys.path.insert(0, os.path.abspath(os.path.join(_STUDY, "..", "..")))

from hedgers_toll import data, extension
from quantlab.repro import DEFAULT_AS_OF, as_of, fingerprint

OUT = os.path.join(_STUDY, "docs", "extension.md")
COST_BPS = 10.0


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--fetch", action="store_true")
    args = ap.parse_args()
    hp = data.fetch_cot(fetch=args.fetch); fut = data.fetch_futures(fetch=args.fetch)
    if hp.empty or fut.empty:
        print("[skip] no cached COT/futures -- run with --fetch first."); return
    fut = as_of(fut, DEFAULT_AS_OF)
    hpA = data.align_hp(hp, fut)
    fp = fingerprint(pd.concat([fut, hpA.add_prefix("hp_")], axis=1).round(6))
    sw = extension.window_sweep(fut, hpA, cost_bps=COST_BPS)
    ls = extension.leg_split(fut, hpA, cost_bps=COST_BPS)
    print(sw.round(3).to_string()); print(ls)
    _write(OUT, sw, ls, fp, DEFAULT_AS_OF, hpA.dropna(how="all").index.min().date(), fut.index.max().date(), fut.shape[1])
    print(f"\nwrote {OUT}")


def _write(path, sw, ls, fp, asof, lo, hi, n_comm):
    rows = "\n".join(f"| {int(k)} | {r['ls_sharpe']:+.2f} |" for k, r in sw.iterrows())
    text = f"""# Beat 7 — worked complement: is the (absent) premium a window artefact? (Study 29)

*Generated by [`examples/extension.py`](../examples/extension.py) on real CFTC COT + {n_comm} commodity
futures. As-of **{asof}**, {lo} → {hi}, fingerprint `{fp}`.*

## Not a tuning problem — it just isn't there

If the hedging-pressure premium had merely the wrong lookback, some signal-normalisation window would
rescue it. None does — the long-short Sharpe is negative across the board:

| signal window (weeks) | long-short Sharpe |
|---|---|
{rows}

And splitting the book shows the long leg (the speculator supposedly *paid* to absorb hedgers' risk)
carries no premium either: long-only-top Sharpe **{ls['long_only_top_sharpe']:+.2f}**, long-short
**{ls['long_short_sharpe']:+.2f}**, vs the equal-weight basket **{ls['basket_sharpe']:+.2f}**.

**Takeaway.** `WEAK` / `MIRAGE` / `Faded` survives the worked complement. The hedging-pressure premium is
real in the long-run academic record and on our synthetic control, but on the modern commodity tape it is
absent at every parameter — competed away, or specific to the longer, broader samples the original
studies used. A real risk premium that a present-day trader cannot collect.
"""
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


if __name__ == "__main__":
    main()
