             "print('CL=F per-month stats (n~26 each):')\n"
             "print(f'{\"Month\":6s}  {\"Mean\":>8s}  {\"t-stat\":>8s}  {\"n\":>4s}  Signal?')\n"
             "bonferroni_t = 3.0  # approx |t| for alpha=0.05/12\n"
