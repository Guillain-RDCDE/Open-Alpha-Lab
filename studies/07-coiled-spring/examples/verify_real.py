"""Real-data run — the headline numbers behind Study 07's verdict.

Loads the cached liquid US universe (the parquets Study 04 cached, split-only), winsorizes
bad prints, finds every 20-EMA pivot breakout, and runs the full teardown:

    detector sanity (synthetic recall)  ->  signal vs same-stock random entry (the headline
    falsification)  ->  tradable ledger + bootstrap Sharpe  ->  the "explosive move" audit
    (how many trades actually do the book's +30%)  ->  cost sweep  ->  decay by year  ->
    capacity.

    python examples/verify_real.py

Prints every table and writes a reproducible results doc (as-of date + a content
fingerprint of the price inputs) to docs/results.md, so the README verdict traces to an
exact run. Cache-only: names with no parquet are skipped, never silently re-downloaded.
"""

import os
import sys

import numpy as np
import pandas as pd

_STUDY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _STUDY)
sys.path.insert(0, os.path.abspath(os.path.join(_STUDY, "..", "..")))

from coiled_spring import backtest, data, robustness, signals
from quantlab.repro import DEFAULT_AS_OF, fingerprint

pd.set_option("display.width", 200)
pd.set_option("display.max_columns", 20)
pd.set_option("display.float_format", lambda v: f"{v:,.4f}")

OUT = os.path.join(_STUDY, "docs", "results.md")
COST_BPS = 15.0          # round-trip, large-cap US (swept in the cost table)
HORIZONS = (5, 10, 20)


def _close_panel(frames):
    return pd.DataFrame({t: f["Close"] for t, f in frames.items()}).sort_index()


def main():
    asof = DEFAULT_AS_OF
    p = signals.Params()

    # 0) Machinery sanity on ground truth — the detector finds planted springboards offline.
    syn_frames, truth = data.synthetic_universe(seed=0)
    recall = robustness.detector_recall(syn_frames, truth)

    # 1) Real universe.
    frames = data.load_universe(mode=data.DEFAULT_MODE, min_rows=750, asof=asof)
    panel = _close_panel(frames)
    fp = fingerprint(panel.fillna(0.0), round_dp=4)
    print(f"universe: {len(frames)} names, {panel.index.min().date()} -> {panel.index.max().date()}")
    print(f"detector recall on synthetic: {recall}")

    sigs = backtest.signals_by_ticker(frames, p)        # one detection pass, reused below
    n_sig = sum(len(s) for s in sigs.values())
    n_names = sum(len(s) > 0 for s in sigs.values())
    print(f"signals: {n_sig} breakouts across {n_names} names")

    # 2) Headline falsification.
    sb = robustness.signal_vs_baseline(frames, p, horizons=HORIZONS, sigs=sigs)
    print("\n[signal vs same-stock random baseline]\n", sb.round(4).to_string())

    # 3) Tradable ledger.
    led = backtest.run_universe(frames, params=p, cost_bps=COST_BPS, sigs=sigs)
    stats = backtest.trade_stats(led)
    boot = robustness.trade_sharpe_ci(led)
    print("\n[trade stats]\n", {k: (round(v, 4) if isinstance(v, float) else v) for k, v in stats.items()})
    print("[per-trade net Sharpe CI]", {k: round(v, 4) for k, v in boot.items()})

    # 4) Distribution of net returns (the part the book never shows).
    pcts = led["ret_net"].quantile([0.05, 0.25, 0.5, 0.75, 0.95]).round(4).to_dict() if len(led) else {}
    reasons = led["exit_reason"].value_counts(normalize=True).round(3).to_dict() if len(led) else {}
    print("[net return percentiles]", pcts)
    print("[exit reasons]", reasons)

    # 5) Costs, decay, capacity.
    sweep = robustness.cost_sweep(frames, p, sigs=sigs)
    decay = robustness.decay_by_year(frames, p, cost_bps=COST_BPS, sigs=sigs)
    dvol = pd.concat([data.dollar_volume(f) for f in frames.values()])
    cap = robustness.capacity(dvol, led)
    print("\n[cost sweep]\n", sweep.round(4).to_string())
    print("\n[decay by year]\n", decay.round(4).to_string())
    print("[capacity]", {k: (round(v, 0) if isinstance(v, float) else v) for k, v in cap.items()})

    _write_results(OUT, frames, panel, recall, sb, stats, boot, pcts,
                   reasons, sweep, decay, cap, asof, fp, p)
    print(f"\nwrote {OUT}")


def _write_results(path, frames, panel, recall, sb, stats, boot, pcts,
                   reasons, sweep, decay, cap, asof, fp, p):
    def md(df):
        return "```\n" + df.round(4).to_string() + "\n```"

    def d(x):
        return {k: (round(v, 4) if isinstance(v, float) else v) for k, v in x.items()}

    with open(path, "w", encoding="utf-8") as fh:
        fh.write(f"""# Results — Study 07 (Coiled-Spring) on the cached liquid universe

*Generated by [`examples/verify_real.py`](../examples/verify_real.py). Universe: the cached
deep-history US names (split-only prices — see the data-mode note in
[`coiled_spring/data.py`](../coiled_spring/data.py)). Rule: 20-EMA pivot breakout, pivot =
local high over ±{p.pivot_halfwin} bars after a spell below the EMA, pullback must **hold
the EMA in close**, breakout = first close above the pivot on **volume ≥ {p.vol_mult:g}×** the
trailing {p.vol_window}-day average; enter next open, stop under the breakout bar's low,
trail under the prior bar's low in profit, {backtest.ExitRules().max_hold}-session max hold.
Round-trip cost **{COST_BPS:g} bps**. As-of **{asof}**. Price fingerprint **`{fp}`**
({len(frames)} names, {panel.index.min().date()} → {panel.index.max().date()}).*

> **Machinery sanity first.** On the offline synthetic universe (planted springboards hidden
> among random walks) the detector recalls **{recall['recall']:.0%}** of planted breakouts
> ({recall['n_hit']}/{recall['n_planted']}) and the backtest harvests their runs — so the
> rule *fires and pays where the structure is really there*. Whatever the real data says
> below is therefore the market talking, not a broken detector.

## Headline — does a breakout beat just being long the same stock?
*Forward return after a breakout vs the mean forward return of **random entries in the same
name** over the same horizon. The excess is the object tested (Newey-West t, bootstrap).*

{md(sb)}

## The tradable strategy — {stats.get('n_trades', 0)} trades, net of {COST_BPS:g} bps
`{d(stats)}`
- per-trade net Sharpe (not annualised), bootstrap CI: `{d(boot)}`
- net-return percentiles: `{pcts}`
- exit reasons: `{reasons}`

## The "explosive move" audit
The book sells the rule on +30-50% pops in 6-10 days. Across **all** {stats.get('n_trades', 0)}
trades, the share that gross **≥ +30%** is **{stats.get('pct_explosive', float('nan')):.1%}**;
the median net trade is **{stats.get('median_net', float('nan')):+.2%}** and the average hold
is **{stats.get('avg_bars_held', float('nan')):.0f}** sessions.

## Cost sweep — round-trip bps → mean net per trade
{md(sweep)}

## Decay by year — the same rule, sliced by entry year
{md(decay)}

## Capacity (per name, 1% participation)
`{ {k: (round(v, 0) if isinstance(v, float) else v) for k, v in cap.items()} }`
""")


if __name__ == "__main__":
    main()
