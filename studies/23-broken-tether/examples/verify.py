"""Real-data run — do real ETF pairs stay cointegrated enough to trade?

Three questions (the offline core proves the machine on a baked cointegrated pair; this points it at
the market):

  * **Is the spread mean-reverting?** The half-life of each candidate pair's spread.
  * **Does it survive out of sample?** First-half vs second-half Sharpe of the causal pairs book —
    across every candidate pair, not one.
  * **Is apparent cointegration real or selection?** The false-positive rate among independent random
    walks, and the hedge-ratio drift of a representative pair.

    python examples/verify.py --fetch     # populate the close cache (network)
    python examples/verify.py             # offline, cache-only

Network lives only behind `--fetch`. Pinned with `quantlab.repro.as_of` and fingerprinted. Data choice:
split-only closes in log space; both legs charged the same series.
"""

import argparse
import itertools
import os
import sys

import numpy as np
import pandas as pd

_STUDY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _STUDY)
sys.path.insert(0, os.path.abspath(os.path.join(_STUDY, "..", "..")))

from broken_tether import data, spread, strategy, decompose, extension
from quantlab.repro import DEFAULT_AS_OF, as_of, fingerprint

OUT = os.path.join(_STUDY, "docs", "results.md")
COST_BPS = 2.0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fetch", action="store_true")
    args = ap.parse_args()

    closes = data.fetch_closes(fetch=args.fetch)
    if not closes:
        print("[skip] no cached closes -- run with --fetch first.")
        return
    closes = {tk: as_of(c.to_frame(), DEFAULT_AS_OF)[tk] for tk, c in closes.items()}

    scan = extension.oos_scan(closes, cost_bps=COST_BPS, max_pairs=45)
    n_survive = int(scan["survives"].sum())
    n_pairs = len(scan)
    # half-lives across pairs
    hls = []
    for a_tk, b_tk in itertools.islice(itertools.combinations(closes, 2), 45):
        hls.append(spread.half_life(spread.spread(closes[a_tk], closes[b_tk])))
    hls = np.array([h for h in hls if np.isfinite(h)])
    spur = decompose.spurious_pairs(n_series=20, seed=1)

    # a representative best-in-first-half pair, to show it breaks
    best_is = scan.sort_values("first_half", ascending=False).iloc[0]
    best_pair = best_is.name
    a_tk, b_tk = best_pair.split("/")
    drift = extension.hedge_ratio_drift(closes[a_tk], closes[b_tk])

    allc = pd.DataFrame(closes)
    fp = fingerprint(allc.round(6))
    print(f"{n_survive}/{n_pairs} real pairs survive OOS; spurious FP rate {spur['false_positive_rate']:.0%}")
    print(f"best in-sample pair {best_pair}: {best_is['first_half']:+.2f} -> {best_is['second_half']:+.2f}, beta drift {drift['beta_rel_drift']:.0%}")

    _write(OUT, dict(scan=scan, n_survive=n_survive, n_pairs=n_pairs, med_hl=float(np.median(hls)),
                     spur=spur, best_pair=best_pair, best_is=best_is, drift=drift, fp=fp,
                     lo=allc.index.min().date(), hi=allc.index.max().date(), n_etf=len(closes)), DEFAULT_AS_OF)
    print(f"\nwrote {OUT}")


def _verdict(d):
    surv_rate = d["n_survive"] / d["n_pairs"]
    signal = "REAL" if surv_rate > 0.5 else "WEAK"
    trad = "INVESTABLE" if surv_rate > 0.5 else "MIRAGE"
    tether = "Confirmed" if surv_rate > 0.5 else "Breaks"
    return signal, trad, tether


def _write(path, d, asof):
    signal, trad, tether = _verdict(d)
    top = d["scan"].sort_values("first_half", ascending=False).head(10)
    scan_rows = "\n".join(
        f"| {pair} | {r['first_half']:+.2f} | {r['second_half']:+.2f} | {'✅' if r['survives'] else '❌'} |"
        for pair, r in top.iterrows()
    )
    bi = d["best_is"]
    text = f"""# Results — Study 23 (Broken-Tether) on real ETF pairs

*Generated by [`examples/verify.py`](../examples/verify.py). Daily split-only closes; the strategy is a
causal z-score pairs trade (trailing hedge ratio and z-score, enter at ±1.5σ, exit near the mean),
{COST_BPS:.0f} bp per leg per turn. The offline core proves the machinery on a synthetic *cointegrated*
pair (and a spurious one); this is the measurement on the market. As-of **{asof}**; match the
fingerprint below. Split-only closes in log space — stated, not hidden.*

## The verdict, earned — Signal `{signal}` · Tradability `{trad}` · Stays tethered? `{tether}`

Pairs trading works beautifully on a *truly* cointegrated pair — but real ETF pairs won't sit still.
Across **{d['n_pairs']}** candidate pairs, only **{d['n_survive']}** clears a 0.3 Sharpe out of
sample: a pair that looks great in the first half almost always limps or breaks in the second. The
poster child here is **{d['best_pair']}**, the best first-half pair at Sharpe
**{bi['first_half']:+.2f}** — which falls to **{bi['second_half']:+.2f}** in the second half, while its
trailing hedge ratio drifts by **{d['drift']['beta_rel_drift']:.0%}** of its own level (the tether
stretching). And the search itself is a trap: **{d['spur']['false_positive_rate']:.0%}** of *independent
random walks* look cointegrated by chance, so a universe scan surfaces mostly luck. A real mechanism, an
unstable relationship, a thin and decaying edge.

## Data stamp

- **Basket** ({d['n_etf']} ETFs, {d['n_pairs']} pairs): {d['lo']} → {d['hi']}, fingerprint `{d['fp']}`

## Out-of-sample survival, top pairs by first-half Sharpe

| pair | first-half Sharpe | second-half Sharpe | survives? |
|---|---|---|---|
{scan_rows}

Only **{d['n_survive']} of {d['n_pairs']}** pairs survive (second-half Sharpe > 0.3). The first-half
ranking does not carry over — the in-sample winners are mostly *not* the out-of-sample ones, the
signature of an unstable relationship rather than a durable edge.

## Is apparent cointegration real, or selection?

- **Median spread half-life** across real pairs: **{d['med_hl']:.0f} days** — long enough that most
  "pairs" are barely reverting.
- **False-positive rate**: **{d['spur']['n_look_cointegrated']}/{d['spur']['n_pairs']}** =
  **{d['spur']['false_positive_rate']:.0%}** of *independent random walks* show a short spread half-life
  by chance. Scan a big universe and you'll find "cointegrated" pairs that never were.
- **Hedge-ratio drift** ({d['best_pair']}): the trailing β ranges
  **{d['drift']['beta_min']:.2f}–{d['drift']['beta_max']:.2f}** (±**{d['drift']['beta_rel_drift']:.0%}**
  of its mean) — the relationship the trade is built on is a moving target.

Signal `{signal}`, Tradability `{trad}`, Stays tethered? `{tether}`.
"""
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


if __name__ == "__main__":
    main()
