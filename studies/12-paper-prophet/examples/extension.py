"""Worked extension run (beat 7) — the same stack across tailwind vs no-tailwind assets.

Runs the article's stack, unchanged, on a basket of equity indices (strong leverage effect) and
gold / long bonds / USD / oil (weak or absent), then writes a reproducible docs/extension.md. The
prediction under test: the ARIMA forecast is a coin flip with a ≤ 0 increment on *every* asset,
while the vol-targeting lift tracks the leverage effect — i.e. the "edge" is the sizing tailwind,
not the forecast.

    ../../.venv/Scripts/python.exe examples/extension.py
"""

import os
import sys
import warnings

import pandas as pd

warnings.filterwarnings("ignore")

_STUDY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_ROOT = os.path.abspath(os.path.join(_STUDY, "..", ".."))
sys.path.insert(0, _STUDY)
sys.path.insert(0, _ROOT)
os.environ.setdefault("OVERNIGHT_CACHE", os.path.join(_ROOT, "_cache"))

from paper_prophet import extension                       # noqa: E402
from quantlab import data as qdata                        # noqa: E402
from quantlab.repro import DEFAULT_AS_OF, as_of, fingerprint  # noqa: E402

OUT = os.path.join(_STUDY, "docs", "extension.md")
ASOF = DEFAULT_AS_OF


def main():
    tickers = list(extension.DEFAULT_PANEL)
    prices = {}
    fps = {}
    cache_paths = {}
    cache_dir = os.path.join(_STUDY, "out")
    for t in tickers:
        df = as_of(qdata.fetch(t), ASOF)            # cached, or fetched + cached on a miss
        prices[t] = df["Close"]
        fps[t] = fingerprint(df[["Close"]], round_dp=4)
        cache_paths[t] = os.path.join(cache_dir, f"wf_{t}_{fps[t]}.parquet")
        print(f"{t}: {len(df)} rows {df.index.min().date()}->{df.index.max().date()} fp={fps[t]}")

    print("running the stack on each asset (cold, parallel) — a few minutes per asset...")
    panel = extension.run_panel(prices, cache_paths=cache_paths)
    cols = ["n_days", "hit_rate_pct", "dir_hac_t", "sharpe_stack", "sharpe_voltgt",
            "sharpe_buyhold", "arima_increment", "voltgt_lift", "leverage_corr"]
    print(panel[cols].round(3).to_string())

    _write(OUT, panel, fps)
    print(f"\nwrote {OUT}")


def _write(path, panel, fps):
    tw = list(extension.TAILWIND_ASSETS)
    nt = list(extension.NO_TAILWIND_ASSETS)
    show = panel.copy()
    tbl = show[["n_days", "hit_rate_pct", "dir_hac_t", "sharpe_voltgt", "sharpe_buyhold",
                "voltgt_lift", "arima_increment", "leverage_corr"]].round(3)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(f"""# Extension — the same stack across assets with different tailwinds

*Generated by [`examples/extension.py`](../examples/extension.py). The article's ARIMA(1,0,1)+
GARCH(1,1) stack, unchanged, run cold walk-forward on equity indices (**{', '.join(tw)}** — strong
leverage effect) and on **{', '.join(nt)}** (gold / long bonds / USD / oil — weak or absent). As-of
**{ASOF}**; per-ticker close fingerprints: {', '.join(f'{k}=`{v}`' for k, v in fps.items())}.*

## One table

```
{tbl.to_string()}
```

Columns: `hit_rate_pct` / `dir_hac_t` = the ARIMA direction; `sharpe_voltgt` = constant-long with
the same GARCH sizing (pure vol-targeting); `sharpe_buyhold` = plain long; `voltgt_lift` =
vol-targeting Sharpe minus buy-and-hold (the **tailwind**, in Sharpe); `arima_increment` =
Sharpe(stack) − Sharpe(vol-targeting) (the forecast's contribution; **≤ 0 = no edge**);
`leverage_corr` = corr(return, next σ̂) (negative = leverage effect present).

## What it shows

1. **The forecast carries no directional skill that survives scrutiny.** Directional hit-rates sit
   on ~50% (50.1–52.5%), with **|HAC *t*| < 2 on seven of the {len(panel)} assets**. EWJ alone
   grazes the bar (*t* = 2.06 at a 52.0% hit-rate) — exactly the single borderline reading eight
   uncorrected tests are expected to produce, on the asset with no prior claim to the effect.
   Signal `NONE` is not an SPY accident; it is universal.

2. **The ARIMA increment's sign just tracks each asset's drift, not skill.** It is negative on the
   *risers* (SPY −0.35, GLD −0.31, QQQ −0.18: going ~50% short forfeits the climb) and positive on
   the *fallers* (USO +0.29, EWJ, TLT: shorting a sinking asset happens to help). With hit-rates on
   the coin, that is drift mechanics, not forecasting — the forecast adds value nowhere *because*
   it predicts, only where the asset fell anyway.

3. **The sizing tailwind is real but small and not a clean equity-vs-rest split.** The vol-targeting
   lift over buy-and-hold is modest where positive (QQQ +0.28, GLD +0.09, SPY +0.07, USO +0.05) and
   ~zero or negative on EWJ, EWZ, TLT, UUP — *including* equity indices. The leverage-effect proxy
   is noisy. So the headline's "vol-targeting is the part that works" holds on
   the SPY sample but is **not a reliable cross-asset free lunch**: on several tapes the GARCH sizing
   does not even beat holding the asset. The one thing that is rock-solid across all eight is the
   *absence of a forecast edge*.
""")


if __name__ == "__main__":
    main()
