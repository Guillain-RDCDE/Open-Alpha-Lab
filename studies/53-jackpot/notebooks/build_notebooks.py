from __future__ import annotations

import os

import nbformat as nbf
from nbformat.v4 import new_code_cell, new_markdown_cell, new_notebook

HERE = os.path.dirname(os.path.abspath(__file__))

BOOT = """\
import sys, os
sys.path.insert(0, os.path.abspath("../../.."))  # repo root (quantlab/)
sys.path.insert(0, os.path.abspath(".."))        # study package (jackpot/)
%matplotlib inline
import matplotlib.pyplot as plt
plt.rcParams["figure.figsize"] = (10, 5.5); plt.rcParams["axes.grid"] = True
import numpy as np, pandas as pd
from jackpot import data, strategy as st
daily = data.fetch_panel()                     # cache-first
sig = st.max_signal(daily)
textbook = st.cross_section_hedge(daily, sig, long_high=False)   # long low-MAX, short high-MAX
"""

VERDICT = (
    "![Signal: None](https://img.shields.io/badge/Signal-None-c0392b?style=flat-square)\n"
    "![Tradability: Mirage](https://img.shields.io/badge/Tradability-Mirage-c0392b?style=flat-square)\n"
    "![Lottery effect on large caps?: Busted](https://img.shields.io/badge/Lottery_effect_on_large_caps%3F-Busted-8b949e?style=flat-square)\n\n"
)


def md(t):
    return new_markdown_cell(t)


def code(t):
    return new_code_cell(t)


def build_curious():
    cells = [
        md("# Jackpot 🎰\n### \"Avoid the lottery stocks\" — sound advice that backfired on large caps\n\n"
           + VERDICT +
           "Behavioural finance says investors overpay for stocks with recent jackpot-like daily gains, "
           "so those high-'MAX' stocks should underperform. On large-cap stocks the trade *lost* — and "
           "kept losing — because the high-volatility names were exactly the growth winners that led the "
           "market. The lottery premium is real, but it lives where you can't easily trade it.\n\n"
           "> 📓 **Plain-language layer.** The t-stat and the inversion are in "
           "**[02_for_the_quants.ipynb](02_for_the_quants.ipynb)**.\n>\n"
           "> ⚠️ **Not investment advice.** Every chart is generated by the code beside it."),
        code(BOOT),
        md("## The answer first 🎯\n\n"
           "| The claim | On large caps (2000–2026) |\n|---|---|\n"
           "| \"High-MAX stocks underperform\" | They **out**performed: textbook trade **−10.4%/yr**. |\n"
           "| \"Short the lottery names\" | Shorting them *cost* you (Sharpe −0.49, t −2.5). |\n"
           "| \"A robust behavioural edge\" | The inversion grew over time (−0.40 → −0.71). |"),
        md("## 1 · The claim\n\nBali, Cakici & Whitelaw (2011): rank stocks by MAX — the average of their "
           "few biggest daily gains last month — and the high-MAX names disappoint, because gamblers bid "
           "them up. Long low-MAX, short high-MAX."),
        md("## 2 · So what?\n\nIf true, you earn a premium for being the boring counterparty to lottery "
           "buyers. But high-MAX is a high-risk proxy, and whether 'avoiding risk' pays depends entirely "
           "on the regime and the universe."),
        md("## 3 · How would we even know?\n\nRank large-cap names by MAX each month, run the textbook "
           "long-low/short-high trade, and check the sign and significance — and how it evolved."),
        code("s=st.stats(textbook)\n"
             "eq=(1+textbook).cumprod()\n"
             "ax=eq.plot(title=f\"Growth of $1, textbook lottery trade (long low-MAX / short high-MAX) — mean {s['mean_ann']:+.0%}/yr, t={s['tstat']:.1f}\",lw=1.8)\n"
             "ax.axhline(1.0,color='k',lw=.8,ls='--'); ax.set_ylabel('growth of $1'); plt.show()"),
        md("## 4 · The teardown\n\nThe line drifts down — shorting the high-MAX names lost money, the "
           "opposite of the anomaly. And it got worse in the 2010s growth run."),
        code("for lab,sl in [('2000-2012',textbook.loc[:'2012']),('2013-on',textbook.loc['2013':])]:\n"
             "    print(f'{lab}: Sharpe {st.stats(sl)[\"sharpe\"]:+.2f}, mean {st.stats(sl)[\"mean_ann\"]:+.2%}/yr')"),
        md("**Read it plainly.** On liquid large caps the high-volatility, high-MAX names *won* — the "
           "same regime that sank [betting against beta](../../43-free-lunch/). The lottery premium hides "
           "in micro-caps; survivorship turns it inside out here."),
        md("## 5 · The verdict\n\n**Signal: None** — the trade lost (t −2.5). **Tradability: Mirage** — "
           "negative gross, worsening. **Lottery effect on large caps?: Busted.**"),
        md("## 6 · Could you actually trade it?\n\nNot on liquid stocks — you'd be short the very names "
           "that led the market. The documented premium requires the small, illiquid, retail-heavy names "
           "(and the delisted blow-ups survivorship hides) — the untradable end."),
        md("## 7 · Going further 🚪\n\nMAX is essentially a volatility proxy — see its near-twin "
           "[Study 54 Static](../../54-static/) (idiosyncratic volatility), which inverts for the same reason."),
    ]
    _write(new_notebook(cells=cells, metadata=_meta()), "01_for_the_curious.ipynb")


def build_quants():
    cells = [
        md("# Jackpot — a quantitative teardown 🔬\n### The textbook hedge with a Lo t-stat · the strengthening inversion · micro-caps, survivorship, regime\n\n"
           + VERDICT +
           "The deep companion to the [notebook for the curious](01_for_the_curious.ipynb). We show the "
           "lottery trade inverts on tradable large caps and why.\n\n"
           "> ⚠️ **Not investment advice.** 436 S&P 500 names, daily, 2000–2026 (Yahoo); survivorship-"
           "biased, large-cap. Sources in [`docs/references.md`](../docs/references.md)."),
        code(BOOT),
        md("## Verdict, up front\n\n| Axis | Stamp | Why |\n|---|---|---|\n"
           "| Signal | **None** | textbook trade −10.4%/yr, Sharpe −0.49, t −2.5 |\n"
           "| Tradability | **Mirage** | negative gross, inversion strengthening |\n"
           "| Large-cap lottery? | **Busted** | premium lives in micro-caps |\n\n"
           "> 💡 *In plain words:* the high-risk names won; the anomaly is a small-cap effect."),
        md("## 1 · The claim, steelmanned\n\n- **H₁:** the long-low/short-high MAX trade earns a positive "
           "premium.\n- **H₂:** it's stable.\n- **H₃:** it survives on tradable large caps."),
        md("## 2 · So what? — what rides on each\n\nIf H₁/H₃ hold, you're paid to avoid lottery stocks "
           "anywhere. If they fail on large caps, the premium is a micro-cap, survivorship-fragile effect."),
        md("## 3 · How we'd know — the protocol\n\nMAX each month → long-low/short-high → Lo t-stat → "
           "decade split."),
        md("## 4 · The teardown"),
        md("### 4.1 The textbook trade"),
        code("import pandas as pd\n"
             "display(pd.Series(st.stats(textbook)).round(3))"),
        md("> 💡 *In plain words:* negative and significant (t −2.5). **H₁ rejected** — it inverted."),
        md("### 4.2 The inversion strengthened"),
        code("for lab,sl in [('2000-2012',textbook.loc[:'2012']),('2013-on',textbook.loc['2013':])]:\n"
             "    print(f'{lab}: Sharpe {st.stats(sl)[\"sharpe\"]:+.2f}')"),
        md("> 💡 *In plain words:* −0.40 → −0.71 as the high-vol growth survivors compounded. **H₂ rejected.**"),
        md("### 4.3 Why — three reasons"),
        md("1. **MAX is a high-risk proxy** (vol/beta); on large caps 2000–2026 high risk *won* (mirror of "
           "[43 Free-Lunch](../../43-free-lunch/)).\n2. **Survivorship**: the high-MAX blow-ups that "
           "delisted are gone; the high-MAX *survivors* did well.\n3. **It's a micro-cap effect** "
           "(Hou-Xue-Zhang 2020) — the untradable end. **H₃ rejected.**"),
        md("## 5 · The verdict\n\nH₁, H₂, H₃ all rejected → Signal `NONE`, Tradability `MIRAGE`, "
           "large-cap lottery `BUSTED`."),
        md("## 6 · Could you trade it?\n\nNot on liquid names. The premium is real in small/illiquid "
           "stocks, where shorting is costly and survivorship is worst — exactly where backtests flatter."),
        md("## 7 · Going further\n\nForks: (a) a point-in-time micro-cap universe (where the effect "
           "should reappear); (b) value-weighting; (c) MAX vs idio-vol head-to-head — see "
           "[Study 54 Static](../../54-static/). Backlog: "
           "[`docs/pwb_strategies_inventory.md`](../../../docs/pwb_strategies_inventory.md)."),
    ]
    _write(new_notebook(cells=cells, metadata=_meta()), "02_for_the_quants.ipynb")


def _meta():
    return {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"}}


def _write(nb, name):
    path = os.path.join(HERE, name)
    with open(path, "w", encoding="utf-8") as f:
        nbf.write(nb, f)
    print("wrote", path)


if __name__ == "__main__":
    build_curious()
    build_quants()
