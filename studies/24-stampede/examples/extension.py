"""Beat-7 worked complement on the real tape — risk-managed momentum (taming the crash).

The headline catch is the crash: WML's fat negative tail wrecks the long-run record. The crashes are
forecastable — they cluster when the factor's own recent volatility is high — so scaling the position by
the inverse of trailing WML vol (a vol-target overlay, exactly Study 16's machinery) cuts the worst
drawdowns and lifts the Sharpe (Barroso & Santa-Clara 2015). This script measures it on the real S&P 500
and writes `docs/extension.md`.

    python examples/extension.py            # cache-only
    python examples/extension.py --fetch
"""

import argparse
import os
import sys

_STUDY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _STUDY)
sys.path.insert(0, os.path.abspath(os.path.join(_STUDY, "..", "..")))

from stampede import data, extension, decompose
from quantlab.repro import DEFAULT_AS_OF, as_of, fingerprint

OUT = os.path.join(_STUDY, "docs", "extension.md")
COST_BPS = 5.0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fetch", action="store_true")
    args = ap.parse_args()

    rets = data.fetch_panel(fetch=args.fetch)
    if rets.empty:
        print("[skip] no cached S&P 500 panel -- run with --fetch first.")
        return
    rets = as_of(rets, DEFAULT_AS_OF)
    fp = fingerprint(rets.round(6))

    cc = extension.crash_comparison(rets, cost_bps=COST_BPS)
    cr = decompose.crash_profile(rets, cost_bps=COST_BPS)
    print(f"plain SR {cc['plain']['sharpe']:+.2f} (DD {cc['plain']['max_drawdown_pct']:.0f}%) -> "
          f"managed SR {cc['managed']['sharpe']:+.2f} (DD {cc['managed']['max_drawdown_pct']:.0f}%)")

    _write(OUT, cc, cr, fp, DEFAULT_AS_OF, rets.index.min().date(), rets.index.max().date(), rets.shape[1])
    print(f"\nwrote {OUT}")


def _write(path, cc, cr, fp, asof, lo, hi, n_stocks):
    p, m = cc["plain"], cc["managed"]
    text = f"""# Beat 7 — worked complement: risk-managed momentum (Study 24, Stampede)

*Generated by [`examples/extension.py`](../examples/extension.py) on the current S&P 500. As-of
**{asof}**, {n_stocks} names, {lo} → {hi}, fingerprint `{fp}`.*

## The crash is forecastable — so it can be tamed

Plain momentum's record is dominated by a few catastrophic months: a worst month of
**{cr['worst_month_pct']:+.1f}%** and a maximum drawdown of **{cr['max_drawdown_pct']:.0f}%**, when
beaten-down losers violently rebound and the short leg detonates. But those crashes cluster when the WML
factor's *own* recent volatility is high (Barroso & Santa-Clara 2015) — so scaling the position by the
inverse of trailing WML vol (the [Study 16](../../16-storm-shy/) vol-target overlay) sidesteps the worst
of them.

| | plain WML | vol-managed WML |
|---|---|---|
| Sharpe | {p['sharpe']:+.2f} | {m['sharpe']:+.2f} |
| monthly skew | {p['skew']:+.2f} | {m['skew']:+.2f} |
| worst month | {p['worst_month_pct']:+.1f}% | {m['worst_month_pct']:+.1f}% |
| max drawdown | {p['max_drawdown_pct']:.0f}% | {m['max_drawdown_pct']:.0f}% |

Vol-scaling lifts the Sharpe (**{p['sharpe']:+.2f} → {m['sharpe']:+.2f}**) and, more importantly, cuts
the drawdown (**{p['max_drawdown_pct']:.0f}% → {m['max_drawdown_pct']:.0f}%**) — the crash is managed,
not eliminated.

**Takeaway.** `WEAK` / `FRAGILE` / `Severe` stands — but the worked complement shows the *Severe* crash
is the manageable part: the same risk-forecasting insight that earned [Study 16](../../16-storm-shy/) the
desk's only green turns momentum's catastrophic tail into a merely uncomfortable one. The premium's
faintness on the modern large-cap sample is the deeper problem; the crash is the one you can engineer
around (at the cost of leverage in calm regimes).
"""
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


if __name__ == "__main__":
    main()
