"""Beat-7 extensions — do the obvious modern fixes rescue the naive GGR rule?

Runs three forks on the **modern era** (where the headline verdict lives), each a single
change to the textbook rule, and reports whether any drags it back over the line:

    1. stop-loss        — cap the per-episode loss (the −85%-drawdown short-gamma tail)
    2. cointegration    — keep only pairs whose formation spread passes a Dickey–Fuller
                          mean-reversion gate (an *economic* reason to revert)
    3. selection breadth — trade only the very tightest pairs (offline proxy for the
                          true "broaden the universe" test, which needs a bigger cache)

    python examples/verify_extensions.py

Writes a reproducible table to `docs/extensions.md` (same as-of + fingerprint as the
headline run), which beat 7 of the README quotes.
"""

import os
import sys

import pandas as pd

_STUDY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _STUDY)
sys.path.insert(0, os.path.abspath(os.path.join(_STUDY, "..", "..")))

from pairs_trading import backtest, data, robustness
from quantlab.repro import DEFAULT_AS_OF, fingerprint

pd.set_option("display.width", 200)
pd.set_option("display.float_format", lambda v: f"{v:,.4f}")

OUT = os.path.join(_STUDY, "docs", "extensions.md")
TOP_N, FORM, TRADE, K, WAIT = 20, 252, 126, 2.0, 1
MODERN_START = "2004-01-01"


def main():
    asof = DEFAULT_AS_OF
    frames = data.load_universe(mode="split_only", min_rows=750, asof=asof)
    panel = data.clean_panel(data.close_panel(frames))   # winsorize bad prints (BMW +6.2M%, ...)
    modern = panel.loc[MODERN_START:]
    fp = fingerprint(panel.fillna(0.0), round_dp=4)
    print(f"modern era: {modern.index.min().date()} -> {modern.index.max().date()}, "
          f"{modern.shape[1]} names")

    base = dict(top_n=TOP_N, form_len=FORM, trade_len=TRADE, k=K, wait=WAIT)
    variants = {
        "baseline (naive rule)":        backtest.run(modern, **base),
        "+ stop-loss 10%":             backtest.run(modern, **base, stop_loss=0.10),
        "+ cointegration gate (DF)":   backtest.run(modern, **base, cointegration=True),
        "+ both fixes":                backtest.run(modern, **base, stop_loss=0.10, cointegration=True),
    }
    table = pd.DataFrame([robustness._row(name, res) for name, res in variants.items()]).set_index("variant")

    sl_scan = robustness.stop_loss_scan(modern, **base)
    tn_scan = robustness.top_n_scan(modern, form_len=FORM, trade_len=TRADE, k=K, wait=WAIT)

    print("\n[fixes vs baseline, modern era]\n", table.round(4))
    print("\n[stop-loss scan]\n", sl_scan.round(4))
    print("\n[selection-breadth (top_n) scan]\n", tn_scan.round(4))

    _write(OUT, modern, table, sl_scan, tn_scan, asof, fp)
    print(f"\nwrote {OUT}")


def _write(path, modern, table, sl_scan, tn_scan, asof, fp):
    def md(df):
        return "```\n" + df.round(4).to_string() + "\n```"
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(f"""# Extensions — Study 05 (Twin-Spread), beat 7 worked

*Generated by [`examples/verify_extensions.py`](../examples/verify_extensions.py). Each
row is one change to the textbook rule, on the **modern era**
({modern.index.min().date()} → {modern.index.max().date()}, {modern.shape[1]} names),
committed capital, wait=1. As-of **{asof}**, price fingerprint **`{fp}`**. The question:
does any single fix drag the rule back over the line?*

## The three fixes vs the naive baseline
{md(table)}

## Stop-loss scan (fix #1 — cap the short-gamma tail)
{md(sl_scan)}

## Selection-breadth scan (fix #3 proxy — trade only the tightest pairs)
{md(tn_scan)}

> A genuine "broaden to S&P 1500" test needs a larger cache than ships here; the breadth
> scan above is its offline cousin (fewer/tighter vs more/looser selected pairs). Point
> [`data.load_universe`](../pairs_trading/data.py) at a wider parquet cache to run the
> real thing.
""")


if __name__ == "__main__":
    main()
