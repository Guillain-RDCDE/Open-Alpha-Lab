"""Real-data run — is the trend real on a live ETF basket, and is it worth holding?

One rule, four questions (the offline core proves the machine; this points it at the market):

  * **Is the trend real?** A pooled time-series-momentum t-stat and a Newey-West t on the strategy
    stream — does a positive past return predict a positive future one?
  * **Does it beat just holding the basket?** TSMOM net Sharpe vs the equal-weight long-only basket.
  * **Is it still working?** Sub-sample Sharpe across the decades — trend's celebrated 2008 and harder
    2010s.
  * **What is it actually for?** The crisis-convexity test — does it pay in the months the basket
    crashes? That diversification, not the standalone Sharpe, is the real product.

    python examples/verify.py --fetch     # populate the basket cache (network)
    python examples/verify.py             # offline, cache-only

Network lives only behind `--fetch`. The sample is pinned with `quantlab.repro.as_of` and fingerprinted.
Data choices: a diversifying ETF basket and split-only closes — stated, not hidden. The basket is
equity-heavy and retail-accessible (14 ETFs), *not* the 50+ cross-asset futures of the academic studies,
so a thinner result here is about *this menu*, not a refutation of the effect.
"""

import argparse
import os
import sys

import pandas as pd

_STUDY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _STUDY)
sys.path.insert(0, os.path.abspath(os.path.join(_STUDY, "..", "..")))

from trend_follow import data, trend, strategy, decompose, extension
from quantlab.repro import DEFAULT_AS_OF, as_of, fingerprint

OUT = os.path.join(_STUDY, "docs", "results.md")
COST_BPS = 2.0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fetch", action="store_true")
    args = ap.parse_args()

    panel = data.fetch_basket(fetch=args.fetch)
    if panel.empty:
        print("[skip] no cached ETF basket -- run with --fetch first.")
        return
    panel = as_of(panel, DEFAULT_AS_OF)

    pr = trend.predictability(panel)
    cmp = strategy.compare(panel, cost_bps=COST_BPS)
    t = decompose.mean_tstat_hac(strategy.tsmom_returns(panel, cost_bps=COST_BPS))
    a = decompose.basket_alpha(panel, cost_bps=COST_BPS)
    boot = decompose.sharpe_bootstrap(panel, n_boot=2000, seed=0, cost_bps=COST_BPS)
    sub = decompose.subsample_sharpe(panel, cost_bps=COST_BPS)
    cc = extension.crisis_convexity(panel, cost_bps=COST_BPS)
    sw = strategy.cost_sweep(panel)

    fp = fingerprint(panel.round(6))
    print(f"basket {list(panel.columns)} | {len(panel)} days")
    print(f"pooled trend t {pr['pooled_t']:+.1f} | TSMOM SR {cmp['tsmom']['sharpe']:+.2f} vs basket "
          f"{cmp['basket']['sharpe']:+.2f} (gain {cmp['sharpe_gain']:+.2f}), turnover {cmp['turnover_ann']:.1f}x")
    print(f"alpha {a['alpha_ann_pct']:+.1f}% (t{a['alpha_t']:+.1f}) beta {a['beta']:+.2f} | "
          f"crisis convexity: TSMOM {cc['tsmom_crisis_mean_pct']:+.2f}%/mo vs basket {cc['basket_crisis_mean_pct']:+.2f}%/mo")

    _write(OUT, dict(
        tickers=list(panel.columns), n=len(panel), fp=fp,
        lo=panel.index.min().date(), hi=panel.index.max().date(),
        pr=pr, cmp=cmp, t=t, a=a, boot=boot, sub=sub, cc=cc, sw=sw,
    ), DEFAULT_AS_OF)
    print(f"\nwrote {OUT}")


def _verdict(d):
    signal = "REAL" if d["t"]["t_stat"] > 2.5 else "WEAK"
    # survives costs (low turnover) but standalone is thin/decayed -> FRAGILE; only INVESTABLE if it
    # clearly beats the basket AND is significant
    investable = d["cmp"]["sharpe_gain"] > 0.2 and d["a"]["alpha_t"] > 2.5
    trad = "INVESTABLE" if investable else "FRAGILE"
    crisis = "CONFIRMED" if d["cc"]["tsmom_crisis_mean_pct"] > 0 else "NOT_SUPPORTED"
    return signal, trad, crisis


def _write(path, d, asof):
    signal, trad, crisis = _verdict(d)
    sub_rows = "\n".join(
        f"| {r['start']} → {r['end']} | {r['sharpe']:+.2f} |" for _, r in d["sub"].iterrows()
    )
    sweep_rows = "\n".join(
        f"| {int(k)} | {v['sharpe']:+.2f} | {v['ann_return']:+.1%} |" for k, v in d["sw"].iterrows()
    )
    cc = d["cc"]
    crisis_badge = "CONFIRMED" if crisis == "CONFIRMED" else "Not supported"
    text = f"""# Results — Study 20 (Freight-Train) on a real ETF basket

*Generated by [`examples/verify.py`](../examples/verify.py). Daily split-only closes for {len(d['tickers'])}
diversifying ETFs, differenced to returns; the strategy is §10.4 time-series momentum
(`w_i = sign(R_i^252)/sigma_i`, gross-normalised, monthly rebalance) vs the equal-weight long-only
basket. The offline core proves the machinery on a synthetic tape with a known persistent drift; this is
the measurement on the market. As-of **{asof}**; match the fingerprint below. Data choices: split-only
closes; an equity-heavy, retail-accessible 14-ETF menu — *not* the 50+ cross-asset futures of the
academic studies, so a thinner result here is about this menu, not a refutation.*

## The verdict, earned — Signal `{signal}` · Tradability `{trad}` · Crisis hedge? `{crisis_badge}`

The trend is **faint on this basket**: a positive past-year return predicts the next month only weakly
(pooled time-series-momentum *t* = **{d['pr']['pooled_t']:+.1f}**, hit rate
**{d['pr']['hit_rate']:.0%}**), and the strategy's own Newey-West *t* is **{d['t']['t_stat']:+.1f}** — at
the edge of significance. Standalone it earns a Sharpe of **{d['cmp']['tsmom']['sharpe']:+.2f}**,
*below* simply holding the basket (**{d['cmp']['basket']['sharpe']:+.2f}**), and it has **decayed**
(sub-sample Sharpe {d['sub'].iloc[0]['sharpe']:+.2f} → {d['sub'].iloc[-1]['sharpe']:+.2f}). So as a
return engine it is `WEAK`/`FRAGILE`. **But that isn't why anyone holds it.** In the basket's worst
months it *makes money* — **{cc['tsmom_crisis_mean_pct']:+.2f}%/mo** while the basket loses
**{cc['basket_crisis_mean_pct']:+.2f}%/mo** — with a basket beta of **{d['a']['beta']:+.2f}**. The
crisis convexity, the thing trend is actually bought for, is **confirmed**; the standalone Sharpe is a
distraction.

## Data stamp

- **Basket** ({len(d['tickers'])} ETFs): {d['lo']} → {d['hi']}, {d['n']} days, fingerprint `{d['fp']}`

## Is the trend real? (weakly, on this menu)

- Pooled time-series-momentum *t* = **{d['pr']['pooled_t']:+.1f}**, hit rate **{d['pr']['hit_rate']:.0%}**.
- TSMOM net: Sharpe **{d['cmp']['tsmom']['sharpe']:+.2f}**, ann **{d['cmp']['tsmom']['ann_return']:+.1%}**,
  max drawdown **{d['cmp']['tsmom']['max_drawdown']:.0%}**, turnover **{d['cmp']['turnover_ann']:.1f}×/yr**
  (slow — costs are not the threat here).
- Strategy Newey-West *t* = **{d['t']['t_stat']:+.1f}**; alpha vs the basket
  **{d['a']['alpha_ann_pct']:+.1f}%/yr** (*t* = {d['a']['alpha_t']:+.1f}), basket beta **{d['a']['beta']:+.2f}**.
- Bootstrap Sharpe gain over the basket **{d['boot']['sharpe_gain']:+.2f}**, 95% CI
  **[{d['boot']['ci_low']:+.2f}, {d['boot']['ci_high']:+.2f}]**.

## It has decayed

| sub-period | TSMOM net Sharpe |
|---|---|
{sub_rows}

## Costs are not the problem (slow signal)

| cost (bps/unit) | net Sharpe | net ann return |
|---|---|---|
{sweep_rows}

The break-even cost is far above any realistic level — the opposite of [Study 19](../../19-rubber-band/),
whose edge died inside the spread. Here the threat is *decay*, not cost.

## What it's for — crisis convexity (`{crisis_badge}`)

| | TSMOM | long-only basket |
|---|---|---|
| worst {cc['n_crisis_months']} months (basket's worst decile) | **{cc['tsmom_crisis_mean_pct']:+.2f}%/mo** | {cc['basket_crisis_mean_pct']:+.2f}%/mo |
| all other months | {cc['tsmom_calm_mean_pct']:+.2f}%/mo | {cc['basket_calm_mean_pct']:+.2f}%/mo |

Trend earns its keep exactly when the basket is bleeding — a "long volatility", crisis-alpha profile
(convexity **{cc['convexity_pp']:+.2f} pp** vs its own calm months). You don't buy trend for its
standalone Sharpe; you buy it for *this*. Signal `{signal}`, Tradability `{trad}`, Crisis hedge?
`{crisis_badge}`.
"""
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


if __name__ == "__main__":
    main()
