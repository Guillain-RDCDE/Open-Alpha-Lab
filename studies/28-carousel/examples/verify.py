"""Real-data run — does sector momentum rotation beat just holding all the sectors?

Three questions (the offline core proves the machine; this points it at the market):

  * **Does the hot sector stay hot?** The top-minus-bottom sector-momentum spread and its HAC t.
  * **Does rotation beat the equal-weight basket?** Long-only rotation Sharpe vs holding all 11 sectors,
    and the alpha over the basket.
  * **Does it generalise?** The fraction of top-k choices that beat the basket.

    python examples/verify.py --fetch     # populate the sector-ETF cache (network)
    python examples/verify.py             # offline, cache-only

Network only behind `--fetch`. Pinned with `quantlab.repro.as_of` and fingerprinted. Split-only closes
for the 11 SPDR sector ETFs.
"""

import argparse
import os
import sys

import pandas as pd

_STUDY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _STUDY)
sys.path.insert(0, os.path.abspath(os.path.join(_STUDY, "..", "..")))

from carousel import data, rotation, strategy, decompose, extension
from quantlab.repro import DEFAULT_AS_OF, as_of, fingerprint

OUT = os.path.join(_STUDY, "docs", "results.md")
COST_BPS = 3.0


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--fetch", action="store_true")
    args = ap.parse_args()
    rets = data.fetch_sectors(fetch=args.fetch)
    if rets.empty:
        print("[skip] no cached sector ETFs -- run with --fetch first."); return
    rets = as_of(rets, DEFAULT_AS_OF)

    rs = rotation.rotation_strength(rets)
    cmp = strategy.compare(rets, cost_bps=COST_BPS)
    a = decompose.vs_equal_weight(rets, cost_bps=COST_BPS)
    ls = decompose.long_short_tstat(rets, cost_bps=COST_BPS)
    sub = decompose.subsample_sharpe(rets, cost_bps=COST_BPS)
    sw = extension.topk_sweep(rets, cost_bps=COST_BPS)
    fp = fingerprint(rets.round(6))

    print(f"rotation Sharpe {cmp['rotation']['sharpe']:+.2f} vs equal-weight {cmp['equal_weight']['sharpe']:+.2f} "
          f"(gain {cmp['rotation_minus_ew_sharpe']:+.2f}); alpha {a['alpha_ann_pct']:+.1f}% (t {a['alpha_t']:+.1f})")
    _write(OUT, dict(rs=rs, cmp=cmp, a=a, ls=ls, sub=sub, sw=sw, fp=fp,
                     lo=rets.index.min().date(), hi=rets.index.max().date(),
                     n_sec=rets.shape[1], n_days=len(rets)), DEFAULT_AS_OF)
    print(f"\nwrote {OUT}")


def _verdict(d):
    ls, a, sw = d["ls"], d["a"], d["sw"]
    signal = "REAL" if ls["t_stat"] > 2 else "WEAK"
    beats = sw["frac_beat_ew"] > 0.6 and a["alpha_ann_pct"] > 0
    trad = "INVESTABLE" if beats else "MIRAGE"
    generalises = "Confirmed" if sw["frac_beat_ew"] > 0.6 else "Not supported"
    return signal, trad, generalises


def _write(path, d, asof):
    signal, trad, gen = _verdict(d)
    cmp, a, ls, sw = d["cmp"], d["a"], d["ls"], d["sw"]
    sub_rows = "\n".join(f"| {r['start']} → {r['end']} | {r['sharpe']:+.2f} |" for _, r in d["sub"].iterrows())
    k_rows = "\n".join(f"| {int(k)} | {r['rotation_sharpe']:+.2f} | {r['gain_over_ew']:+.2f} |"
                       for k, r in sw["matrix"].iterrows())
    text = f"""# Results — Study 28 (Carousel) on the real SPDR sectors

*Generated by [`examples/verify.py`](../examples/verify.py). Daily split-only closes for the {d['n_sec']}
SPDR sector ETFs; the strategy is the top-3 momentum rotation (126-day lookback, monthly), {COST_BPS:.0f} bp
per unit traded, vs holding all sectors equal-weight. The offline core proves the machinery on a synthetic
sector panel with baked momentum; this is the measurement on the market. As-of **{asof}**; match the
fingerprint below.*

## The verdict, earned — Signal `{signal}` · Tradability `{trad}` · Beats the basket? `{gen}`

Rotating into the hot sectors is the strategy everyone's chart-watching uncle swears by — and on the real
SPDR sectors it **doesn't beat simply owning all of them.** The long-only rotation book earns a Sharpe of
**{cmp['rotation']['sharpe']:+.2f}**, essentially the same as the equal-weight basket
(**{cmp['equal_weight']['sharpe']:+.2f}**, gain **{cmp['rotation_minus_ew_sharpe']:+.2f}**), with an alpha
over the basket of **{a['alpha_ann_pct']:+.1f}%/yr** (HAC *t* = **{a['alpha_t']:+.1f}**) — indistinguishable
from zero. The pure sector-momentum factor (top-minus-bottom) is itself flat-to-negative
(**{ls['mean_ann_pct']:+.1f}%/yr**, *t* = **{ls['t_stat']:+.1f}**), and the rule beats the basket on only
**{sw['frac_beat_ew']:.0%}** of plausible "how many sectors to hold" choices — a coin flip. You take
concentration risk and **{cmp['turnover_ann']:.0f}×/yr** turnover for nothing.

## Data stamp

- **Sectors**: {d['n_sec']} SPDR ETFs, {d['lo']} → {d['hi']}, {d['n_days']} sessions, fingerprint `{d['fp']}`

## Rotation vs holding all sectors

| | Sharpe | ann return | max drawdown |
|---|---|---|---|
| top-3 rotation | {cmp['rotation']['sharpe']:+.2f} | {cmp['rotation']['ann_return']:+.1%} | {cmp['rotation']['max_drawdown']:.0%} |
| equal-weight basket | {cmp['equal_weight']['sharpe']:+.2f} | {cmp['equal_weight']['ann_return']:+.1%} | {cmp['equal_weight']['max_drawdown']:.0%} |

- **Sector-momentum spread**: top-3 minus bottom-3 forward return **{d['rs']['top_minus_bottom_ann_pct']:+.1f}%/yr**.
- **Rotation alpha over the basket**: **{a['alpha_ann_pct']:+.1f}%/yr** (HAC *t* = **{a['alpha_t']:+.1f}**),
  beta **{a['beta']:.2f}**, turnover **{cmp['turnover_ann']:.1f}×/yr**.
- **Long-short factor**: **{ls['mean_ann_pct']:+.1f}%/yr** (*t* = **{ls['t_stat']:+.1f}**) — no momentum
  premium across sectors.

## Sub-sample Sharpe (rotation)

| sub-period | Sharpe |
|---|---|
{sub_rows}

## Does it generalise? (top-k sweep)

| sectors held (top-k) | rotation Sharpe | gain over equal-weight |
|---|---|---|
{k_rows}

Rotation beats the basket on **{sw['frac_beat_ew']:.0%}** of these choices (mean gain
**{sw['mean_gain']:+.2f}**); the best, k = **{sw['best_k']}**, is just the luckiest cell. A rule that
helps at one hand-picked concentration and not the others isn't an edge — it's a coin flip with extra
turnover. Signal `{signal}`, Tradability `{trad}`, Beats the basket? `{gen}`.
"""
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


if __name__ == "__main__":
    main()
